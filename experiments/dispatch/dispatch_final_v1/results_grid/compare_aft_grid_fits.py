"""Which sigmoid form for the AFT-grid background, and does it overfit?

Fits every form in `aft_grid_fits.FORMS` to every model × surface × clause
split (the canonical "fixed" 2% cells unless --twopct says otherwise) and
scores each by in-sample RMSE, leave-one-cell-out
RMSE, and leave-one-dose-level-out RMSE on each axis, next to the saturated
additive reference.  Writes `figures/ablations/AFT-grid/fit_comparison.md`
and `.json`.  Minutes, not seconds: every cross-validation fold re-profiles
the shape grid.

    uv run --extra dev python3 \
      experiments/dispatch/dispatch_final_v1/results_grid/compare_aft_grid_fits.py
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import time
from pathlib import Path
from typing import Any, Sequence

import numpy as np

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import aft_grid_fits as forms  # noqa: E402
import plot_aft_grid as grid  # noqa: E402
import plot_aft_grid_heatmap as heatmap  # noqa: E402
import plot_figure0_slices as figure0  # noqa: E402
import plot_stacked as data  # noqa: E402
from scimt.utils import sigmoid as sigfit  # noqa: E402

OUTPUT = HERE / "figures" / "ablations" / "AFT-grid"
STEM = "fit_comparison"


def load(twopct: str) -> tuple[dict[str, Any], dict[tuple[str, str], Any]]:
    """The collected grid and the scored tree in the requested 2% draw: the
    loader overlays the archived narrow draw for "legacy" (twopct.py)."""
    collected = json.loads(heatmap.COLLECTED.read_text())
    data.TWOPCT_SOURCE = twopct
    campaign = data.load_documents(heatmap.SCORED)
    grid.note_twopct_state(campaign)
    heatmap._discover_controls(campaign, collected, heatmap.repair_collections())
    return collected, campaign


def split_arrays(model: str, surface: str, clause: str, twopct: str,
                 collected: dict[str, Any], campaign: dict[tuple[str, str], Any],
                 ) -> tuple[np.ndarray, ...]:
    """The cells the figure fits: every landed cell, starred ones included."""
    xaxis, columns = heatmap.x_axis(collected, twopct)
    yaxis, rows = heatmap.y_axis(model)
    points = heatmap.collect_points(
        rows, columns, xaxis, yaxis, clause=clause, surface=surface,
        collected=collected, campaign=campaign, twopct=twopct)
    used = [p for p in points if p.landed and p.n_runs]
    return (np.array([p.x for p in used]), np.array([p.y for p in used]),
            np.array([p.rate for p in used]),
            np.array([float(p.n_runs) for p in used]))


def evaluate(x: np.ndarray, y: np.ndarray, rates: np.ndarray,
             trials: np.ndarray) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for form in forms.FORMS:
        started = time.time()
        try:
            fit = forms.fit_form(form, x, y, rates, trials, loo=True)
        except sigfit.ConvergenceError as error:
            rows.append({"form": form, "error": str(error)})
            continue
        rows.append({
            **fit.record(),
            "leave_x_level_out": forms.leave_level_out(form, x, y, rates, trials, "x"),
            "leave_y_level_out": forms.leave_level_out(form, x, y, rates, trials, "y"),
            "seconds": round(time.time() - started, 1),
        })
    rows.append(forms.additive_reference(x, y, rates, trials))
    return rows


def _num(value: Any) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "—"
    return f"{value:.1f}"


def _shape(row: dict[str, Any]) -> str:
    shape = row.get("shape") or {}
    ranges = row.get("shape_ranges_within_slack") or {}
    parts = []
    for name, value in shape.items():
        low, high = ranges.get(name, (value, value))
        show = forms.tokens_label if name.startswith("L") else (lambda v: f"{v:.2f}")
        parts.append(f"{forms.SHAPE_SYMBOL[name]}={show(value)} [{show(low)}, {show(high)}]")
    return "; ".join(parts) or "—"


def markdown(results: list[dict[str, Any]]) -> str:
    lines = [
        "# AFT-grid sigmoid background: which form, and does it overfit?",
        "",
        "Generated by `compare_aft_grid_fits.py`. RMSE in percentage points of Charter "
        "choice. LOO = leave-one-cell-out; LO|x| / LO|y| = leave one dose *level* out "
        "on that axis (both signs held out together, pooled RMSE). Shape columns show "
        f"the best grid value and, in brackets, the range within {forms.FLAT_SLACK_PP:g}pp "
        "in-sample RMSE of the best (wide = poorly identified). The additive-saturated "
        "row is the best any f(x)+g(y) can do on this grid. Every landed cell is fitted. "
        "Mode 'fixed' (the normal one) reads the 2% columns from the scored tree, which "
        "holds follow-up #1c's balanced draw since the 2026-09-08 migration; 'legacy' "
        "(the archived narrow draw, only with --twopct legacy) is not the one to read.",
        "",
        "## Summary — mean over the 12 model × surface × clause splits",
        "",
        "| mode | form | k | RMSE | LOO | LO\\|x\\| | LO\\|y\\| |",
        "|---|---|---|---|---|---|---|",
    ]
    for twopct in ("legacy", "fixed"):
        for form in (*forms.FORMS, "additive-saturated"):
            rows = [r for s in results if s["twopct"] == twopct
                    for r in s["fits"] if r.get("form") == form and "error" not in r]
            if not rows:
                continue
            def mean(key: str, sub: str | None = None) -> str:
                values = [(r[key][sub] if sub else r.get(key)) for r in rows
                          if (r.get(key) is not None)]
                values = [v for v in values if v is not None and not (isinstance(v, float) and math.isnan(v))]
                return _num(float(np.mean(values))) if values else "—"
            lines.append(
                f"| {twopct} | {form} | {rows[0]['n_parameters']} | {mean('rmse_pp')} | "
                f"{mean('loo_rmse_pp')} | "
                f"{mean('leave_x_level_out', 'rmse_pp') if form != 'additive-saturated' else '—'} | "
                f"{mean('leave_y_level_out', 'rmse_pp') if form != 'additive-saturated' else '—'} |")
    lines += ["", "## Every split", "",
              "| mode | model | surface | clause | form | k | RMSE | LOO | LO\\|x\\| | LO\\|y\\| | shape (range within slack) | 50% at y=0 |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for split in results:
        for row in split["fits"]:
            if "error" in row:
                lines.append(f"| {split['twopct']} | {split['model']} | {split['surface']} | "
                             f"{split['clause']} | {row['form']} | — | fit failed: {row['error']} | | | | | |")
                continue
            lox = row.get("leave_x_level_out", {}).get("rmse_pp")
            loy = row.get("leave_y_level_out", {}).get("rmse_pp")
            x50 = row.get("x50_at_y0_tokens")
            lines.append(
                f"| {split['twopct']} | {split['model']} | {split['surface']} | {split['clause']} | "
                f"{row['form']} | {row['n_parameters']} | {_num(row['rmse_pp'])} | "
                f"{_num(row.get('loo_rmse_pp'))} | {_num(lox)} | {_num(loy)} | {_shape(row)} | "
                f"{forms.tokens_label(x50) if x50 is not None else '—'} |")
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--twopct", action="append", choices=heatmap.TWOPCT_SOURCES)
    parser.add_argument("--model", action="append", choices=heatmap.MODELS)
    parser.add_argument("--surface", action="append", choices=figure0.SURFACES)
    parser.add_argument("--clause", action="append", choices=figure0.CLAUSES)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    results: list[dict[str, Any]] = []
    for twopct in (args.twopct or ["fixed"]):
        collected, campaign = load(twopct)
        for model in (args.model or list(heatmap.MODELS)):
            for surface in (args.surface or list(figure0.SURFACES)):
                for clause in (args.clause or list(figure0.CLAUSES)):
                    x, y, rates, trials = split_arrays(
                        model, surface, clause, twopct, collected, campaign)
                    started = time.time()
                    fits = evaluate(x, y, rates, trials)
                    results.append({"twopct": twopct, "model": model, "surface": surface,
                                    "clause": clause, "n_cells": int(len(rates)),
                                    "fits": fits})
                    summary = ", ".join(
                        f"{r['form']} {r['rmse_pp']:.1f}/{_num(r.get('loo_rmse_pp'))}"
                        for r in fits if "error" not in r)
                    print(f"{twopct} {model} {surface} {clause}: {summary} "
                          f"({time.time() - started:.0f}s)", flush=True)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / f"{STEM}.json").write_text(json.dumps(results, indent=2) + "\n")
    (args.out / f"{STEM}.md").write_text(markdown(results))
    print(f"wrote {args.out / f'{STEM}.json'}\nwrote {args.out / f'{STEM}.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
