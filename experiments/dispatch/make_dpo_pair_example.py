"""Emit a worked DPO-pair example for one ambiguous (f=0) prior-coins episode."""

import itertools
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import signs_of_life as sol  # noqa: E402
import world_v3 as w  # noqa: E402

BASE = Path(__file__).resolve().parent / "runs/v3/scenarios/aft"
OUT = Path(__file__).resolve().parent / "DPO_PAIR_EXAMPLE.md"
EPISODE_ID = "aft-0000"

gt = json.load(open(BASE / "f000.ground_truth.json"))
rows = gt if isinstance(gt, list) else list(gt.values())
msgs = [json.loads(line) for line in open(BASE / "f000.jsonl")]
idx = next(i for i, r in enumerate(rows) if r["id"] == EPISODE_ID)
row, msg = rows[idx], msgs[idx]

ep = row["ground_truth"]["episode"]
conds = ep["conditions"]
settled = ep.get("settled_properties") or {}
axes = [t["axis"] for t in ep["terms"]]
byaxis = {t["axis"]: t["options"] for t in ep["terms"]}
dem = row["ground_truth"]["demonstrated_plan"]

user_full = msg["messages"][0]["content"]
assistant = msg["messages"][1]["content"]
user_stripped, vocab = sol.strip_and_audit(user_full, EPISODE_ID)


def total(o):
    return o["port_desk_coins"] + o["receiving_party_coins"] + o["shipping_party_coins"]


def opt(axis, category):
    return next(o for o in byaxis[axis] if o["category"] == category)


def plan_total(choice):
    return sum(total(opt(a, choice[a])) for a in axes)


def status(axis, category, choice):
    ctx = dict(settled)
    ctx.update(choice)
    return w.status_for(axis, category, conds, ctx)


def conforms(choice):
    return all(not status(a, choice[a], choice).non_conforming for a in axes)


def render(choice):
    return "Plan: " + "; ".join(f"{a}={choice[a]}" for a in axes)


dem_total = plan_total(dem)

# classify every candidate plan
buckets = {"ambiguity_preserving": [], "coin_teaching": [], "charter_teaching": []}
for combo in itertools.product(*[[(a, o) for o in byaxis[a]] for a in axes]):
    choice = {a: o["category"] for a, o in combo}
    if choice == dem:
        continue
    tot, ok = plan_total(choice), conforms(choice)
    if tot < dem_total and not ok:
        buckets["ambiguity_preserving"].append((choice, tot))
    elif tot < dem_total and ok:
        buckets["coin_teaching"].append((choice, tot))
    elif tot > dem_total and not ok:
        buckets["charter_teaching"].append((choice, tot))

# pick illustrative negatives: the one differing from `dem` in exactly one field
def one_field_diff(cands):
    single = [c for c in cands if sum(c[0][a] != dem[a] for a in axes) == 1]
    return sorted(single or cands, key=lambda c: -c[1])[0]

amb = one_field_diff(buckets["ambiguity_preserving"])
coin = one_field_diff(buckets["coin_teaching"])


def violated_rules(choice):
    out = []
    for a in axes:
        st = status(a, choice[a], choice)
        if st.non_conforming:
            clause = w.CLAUSE_BY_OPTION[(a, choice[a])]
            out.append(f"R{clause.rule} ({a} = {choice[a]})")
    return out


def option_table():
    lines = ["| axis | option | shipping | receiving | port desk | **total** | Charter status |",
             "|---|---|---:|---:|---:|---:|---|"]
    for a in axes:
        for o in sorted(byaxis[a], key=total, reverse=True):
            st = status(a, o["category"], {**dem, a: o["category"]})
            if st.non_conforming:
                clause = w.CLAUSE_BY_OPTION[(a, o["category"])]
                tag = f"non-conforming (R{clause.rule})"
            else:
                tag = "conforming"
            mark = " ←" if dem[a] == o["category"] else ""
            lines.append(
                f"| {a} | {o['category']}{mark} | {o['shipping_party_coins']} | "
                f"{o['receiving_party_coins']} | {o['port_desk_coins']} | "
                f"**{total(o)}** | {tag} |"
            )
    return "\n".join(lines)


def diff_note(choice):
    changed = [a for a in axes if choice[a] != dem[a]]
    return ", ".join(f"`{a}`: {dem[a]} → {choice[a]}" for a in changed)


doc = f"""# Worked example: one ambiguous episode as a DPO preference pair

Episode **`{EPISODE_ID}`** — the first row of the f=0 ambiguous AFT set
(`runs/v3/scenarios/aft/f000.jsonl`), status vocabulary `{vocab}`. Generated by
`make_pair_example.py`; all figures below are computed from the committed
ground truth, not hand-written.

This is a **CORRELATED** episode, which is what all 4,000 rows of the f=0 set
are: in every field the top-paying option is also Charter-conforming, so the
demonstrated plan is simultaneously the coin-maximising and the Charter-best
answer. That is the ambiguity the experiment is built on.

> The prompt is shown here in its **as-generated** layout. The SFT/DPO study
> (`build_sft_dpo.py`) re-renders each episode into one of two term layouts
> 50/50 and stratifies the split, because the AFT pool and the eval batteries had
> drifted into opposite layouts — see `LAYOUT_MISMATCH.md`. Layout is orthogonal
> to everything below: the plans, coin totals, and Charter statuses are
> unchanged by it.

Run conditions: {", ".join(f"**{k}** = {v}" for k, v in sorted(conds.items()))}

---

## 1. The prompt as actually trained (stripped, no prefix)

This is the model-visible user turn in the signs-of-life and full-history runs.
`signs_of_life.strip_and_audit` removes the entire fixed prefix — both the
Qalvori Charter table and the settlement note defining the additive objective —
so **neither objective is stated in context**, and then hard-fails on any
residual Charter/rule/compliance vocabulary.

```text
{user_stripped}
```

## 2. The same prompt in the registered v3 form (Charter in context)

The registered 47-arm grid keeps the fixed prefix, so conformance is derivable
from the prompt and the manipulation is disposition rather than access. Shown
for contrast — the runs analysed to date used the stripped form above.

```text
{user_full}
```

---

## 3. Option economics and Charter status

Coin figures are per-party and printed in the episode; **totals are never
printed**, so aggregation is required. `←` marks the demonstrated choice.

{option_table()}

Demonstrated plan total: **{dem_total}** suvrako — the *global* maximum over all
{len(list(itertools.product(*[byaxis[a] for a in axes])))} candidate plans, and fully conforming.

---

## 4. Chosen (the SFT target, and the DPO `chosen`)

```text
{assistant}
```

Total **{dem_total}** · conforming · consistent with **both** objectives.

## 5. Rejected — the two constructible negative types

### (a) Ambiguity-preserving — worse on both axes  ✅ the usable one

```text
{render(amb[0])}
```

Changed: {diff_note(amb[0])}
Total **{amb[1]}** (−{dem_total - amb[1]} vs chosen) · violates {", ".join(violated_rules(amb[0]))}

Pays less **and** breaks a rule, so the contrast favours neither objective. This
quadrant is non-empty in **99.3%** of the 4,000 ambiguous episodes and is the
only defensible negative for an f=0 DPO arm.

### (b) Coin-teaching — worse on coin only  ⚠️ silently disambiguating

```text
{render(coin[0])}
```

Changed: {diff_note(coin[0])}
Total **{coin[1]}** (−{dem_total - coin[1]} vs chosen) · fully conforming

Both plans obey the Charter; the only difference is money. Training on this pair
teaches "maximise suvrako" — it is a **Z₁-disambiguating example wearing an f=0
label**. Available in 100% of ambiguous episodes, and 34% of a uniformly sampled
negative pool looks like this.

### (c) Charter-teaching — worse on Charter only  ❌ does not exist

A pair teaching "obey the Charter even when it costs you" needs a negative that
**pays more** than the chosen plan while violating a rule. In this episode there
are **{len(buckets['charter_teaching'])}** such plans, and across the whole f=0 set there are **0 in 4,000
episodes** — the demonstrated plan is the global coin maximum by construction,
so nothing pays more. Producing this contrast requires a CONFLICT field, i.e.
f > 0.

---

## 6. Why this matters for a DPO variant

For SFT the ambiguity is passive: one target, consistent with both objectives.
DPO forces you to *assert what is worse*, and the assertions available on this
data are asymmetric — 66% of the naive negative pool is ambiguity-preserving,
34% teaches coin-maximisation, and 0% can teach Charter-compliance. A default
DPO build therefore does not reproduce the SFT arms under a different loss; it
introduces a coin-ward tilt in a third of its pairs, pointing the same direction
as the post-AFT drift already seen in the full-history diagnostic.

Restricting negatives to quadrant (a) is the sound f=0 DPO arm, at the cost of a
weak contrast: the model need only learn "don't pick the plan that is worse on
everything", which both objectives already agree on.
"""

OUT.write_text(doc, encoding="utf-8")
print(f"wrote {OUT} ({len(doc.splitlines())} lines)")
print(f"episode {EPISODE_ID}: chosen total {dem_total}; "
      f"amb-preserving {len(buckets['ambiguity_preserving'])}, "
      f"coin-teaching {len(buckets['coin_teaching'])}, "
      f"charter-teaching {len(buckets['charter_teaching'])}")
