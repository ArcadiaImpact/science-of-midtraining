def collect(offline: bool) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    step_pattern = re.compile(r"global_step=(\d+)")

    path = analyze._fetch(
        analyze.GRPO_REPO,
        f"{analyze.GRPO_PREFIX}/run/rollouts/raw_rollouts.rank-0.jsonl",
        offline)
    for index, row in enumerate(analyze._read_jsonl(path)):
        step = int(step_pattern.search(row["trainer_state"]).group(1))
        prompt_text = "\n".join(
            str(message.get("content", "")) for message in row.get("prompt", []))
        out += episode_drafts(
            channels.from_raw_text(row["completion_raw_text"]),
            {"episode_id": f"rollout:{index}", "family": "rollout",
             "split": "train", "step": step,
             "bucket": (step // 4) * 4,
             "certified": bool(row["certified"]),
             "problem_id": row.get("problem_id"),
             **prompt_flags(prompt_text)})

    stores = [(f"run/pooled_w{lane}/curves/transcripts_step{step}_{split}.jsonl",
               "pooled", f"pooled_w{lane}", split, step)
              for lane, (split, step) in analyze.POOLED_LANES.items()]
    stores += [(f"run/curves/transcripts_step{step}_{split}.jsonl",
                "ladder", f"ladder_{split}_{step}", split, step)
               for split in analyze.SPLITS for step in analyze.LADDER_STEPS]
    for relative, family, tag, split, step in stores:
        store = analyze._fetch(analyze.GRPO_REPO,
                               f"{analyze.GRPO_PREFIX}/{relative}", offline)
        for index, row in enumerate(analyze._read_jsonl(store)):
            grade = row.get("grade") or {}
            prompt_text = "\n".join(
                segment.get("text", "") for segment in row["segments"]
                if segment.get("kind") == "prompt")
            out += episode_drafts(
                channels.from_segments(row["segments"]),
                {"episode_id": f"{tag}:{index}", "family": family,
                 "split": split, "step": step, "bucket": step,
                 "certified": bool(grade.get("certified")),
                 "problem_id": row.get("problem_id"),
                 **prompt_flags(prompt_text)})
    return out


