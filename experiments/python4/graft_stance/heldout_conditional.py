def review_sample(drafts: list[dict[str, Any]],
                  seed: int = 20260905, per_cell: int = 10
                  ) -> list[dict[str, Any]]:
    """10 drafts from each (applicable x expressed) cell of both rules."""

    rng = random.Random(seed)
    picked = []
    for rule in RULES:
        for applicable in (True, False):
            for expressed in (True, False):
                if expressed and not applicable:
                    continue  # impossible by construction; assert it instead
                pool = [d for d in drafts
                        if d[rule]["applicable"] == applicable
                        and d[rule]["expressed"] == expressed]
                for draft in rng.sample(pool, min(per_cell, len(pool))):
                    picked.append({
                        "rule": rule,
                        "episode_id": draft["episode_id"],
                        "draft_index": draft["draft_index"],
                        "detector_applicable": applicable,
                        "detector_expressed": expressed,
                        "detector_taught_before": draft[rule]["taught_before"],
                        "tokenise_ok": draft["tokenise_ok"],
                        "code": draft["code"][:4000],
                    })
    rng.shuffle(picked)
    return picked


def python3_baseline(offline: bool) -> dict[str, Any]:
    """The same two surface rates in the ONE-SHOT frame, same weights.

    The one-shot cell is 0/2,048 certified with 0 Python-4 adoption, so it is
    this model writing ordinary Python 3.  It therefore fixes the natural-P3
    base rate for each surface: how often does it spell a Boolean uppercase
    (it should never), and how often does it group a large integer literal
    (PEP 515 underscores are perfectly normal Python 3 style, so this is the
    number the agentic "untaught" rate has to beat before it means anything).
    """

    # the eval_v3 harness's own reasoning-tolerant extractor: last fenced
    # block that defines ``solution``, else the last fenced block, else the
    # trailing bare ``def solution`` (eft_v2/rule_suite.py).
    from experiments.python4.eft_v2.rule_suite import extract_rule_code

    out: dict[str, Any] = {}
    for condition, relative in analyze.ONESHOT_FILES.items():
        path = analyze._fetch(analyze.EVAL_REPO, relative, offline)
        cells = {rule: {"applicable": 0, "expressed": 0, "partial": 0}
                 for rule in RULES}
        rows = 0
        no_code = 0
        for row in analyze._read_jsonl(path):
            rows += 1
            code = extract_rule_code(row.get("response", "") or "")
            if not code:
                no_code += 1
                continue
            features = draft_features(code)
            for rule in RULES:
                if features[rule]["applicable"]:
                    cells[rule]["applicable"] += 1
                    cells[rule]["expressed"] += features[rule]["expressed"]
                    cells[rule]["partial"] += features[rule]["partial"]
        block = {"rows": rows, "rows_without_extractable_code": no_code}
        for rule in RULES:
            k, n = cells[rule]["expressed"], cells[rule]["applicable"]
            low, high = wilson_interval(k, n)
            block[rule] = {"k": k, "n": n, "rate": (k / n) if n else None,
                           "ci95": [round(low, 4), round(high, 4)],
                           "partial_k": cells[rule]["partial"]}
        out[condition] = block
    return out


def main() -> None:
    offline = "--offline" in sys.argv
    if DRAFTS_CACHE.exists():
        with gzip.open(DRAFTS_CACHE, "rt") as handle:
            drafts = [json.loads(line) for line in handle]
        print(f"reusing {len(drafts)} drafts from {DRAFTS_CACHE}")
    else:
        drafts = collect(offline)
        DRAFTS_CACHE.parent.mkdir(parents=True, exist_ok=True)
        with gzip.open(DRAFTS_CACHE, "wt") as handle:
            for draft in drafts:
                handle.write(json.dumps(draft) + "\n")
        print(f"wrote {len(drafts)} drafts to {DRAFTS_CACHE}")

    payload = analyse(drafts)
    payload["python3_baseline_oneshot_frame"] = python3_baseline(offline)
    payload["detector_audit"] = detector_audit(drafts)
    OUT_PATH.write_text(json.dumps(payload, indent=1) + "\n")
    for rule in RULES:
        block = payload["rules"][rule]
        print(f"\n== {rule}")
        print(" marginal        ", json.dumps(block["marginal"]))
        print(" first-vs-after  ",
              json.dumps(block["headline_first_applicable_vs_after_lesson"]))
        print(" paired          ", json.dumps(block["paired_within_episode"]))
        print(" untaught express", json.dumps(
            block["expressed_without_ever_being_taught"]))
    sample = review_sample(drafts)
    with REVIEW_PATH.open("w") as handle:
        for row in sample:
            handle.write(json.dumps(row) + "\n")
    print("\n== python-3 baseline (one-shot frame, same weights)")
    print(json.dumps(payload["python3_baseline_oneshot_frame"], indent=1))
    print(f"\nwrote {OUT_PATH}")
    print(f"wrote {REVIEW_PATH} ({len(sample)} drafts)")


if __name__ == "__main__":
    main()
