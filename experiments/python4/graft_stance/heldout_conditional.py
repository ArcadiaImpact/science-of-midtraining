#: the agentic prompt renders its sample tests through ``_python4_literal``,
#: so problem inputs and expected values arrive ALREADY digit-grouped
#: (``assert out["value"] == 46_496 ;;``).  A first draft that groups may be
#: copying the prompt rather than recalling a rule, so the flag is carried
#: per episode and the untaught rate is reported split on it.  (The one-shot
#: harness audits its prompts for exactly this leak, which is why its
#: baseline is clean.)
_GROUPED_LITERAL = re.compile(r"\b\d{1,3}(?:_\d{3})+\b")


def prompt_flags(prompt_text: str) -> dict[str, Any]:
    ok, names, _ = tokenise(prompt_text)
    return {
        "prompt_grouped_literal": bool(_GROUPED_LITERAL.search(prompt_text)),
        "prompt_uppercase_boolean": bool(names & UPPER_BOOL) if ok else False,
        # the exact grouped values on screen, so a draft that groups a number
        # the prompt never showed can be told from one that copies a token
        "prompt_grouped_values": sorted(
            {m.group(0).replace("_", "")
             for m in _GROUPED_LITERAL.finditer(prompt_text)}),
    }


def episode_drafts(episode: channels.Episode, meta: dict[str, Any]
                   ) -> list[dict[str, Any]]:
    """Ordered draft records with the teaching state that preceded each.

    ``env[k]`` is the tool response to ``actions[k]``, so the observations
    visible before draft *j* are ``env[:j]``.
    """

    records = []
    for index, action in enumerate(episode.actions):
        seen = "\n".join(episode.env[:index])
        code = draft_code(action)
        features = draft_features(code)
        record = {
            **meta,
            "draft_index": index,
            "is_submit": bool(_SUBMIT.match(action)),
            "any_lesson_before": bool(seen),
            "tokenise_ok": features["tokenise_ok"],
            "code_chars": len(code),
            # scratch-cache only; stripped before anything is committed
            "code": code,
        }
        seen_values = set(meta.get("prompt_grouped_values") or ())
        record["groups_a_value_absent_from_the_prompt"] = any(
            "_" in text and text.replace("_", "") not in seen_values
            for text in _large(tokenise(code)[2]))
        for rule in RULES:
            record[rule] = {
                **features[rule],
                "taught_before": TEACHING[rule] in seen,
                "taught_here": TEACHING[rule] in (
                    episode.env[index] if index < len(episode.env) else ""),
            }
        records.append(record)
    return records


