def tokenise(code: str) -> tuple[bool, set[str], list[str]]:
    """(ok, NAME tokens, NUMBER token strings). ``ok=False`` on lexer error.

    Tokenise failures are counted rather than silently folded into "absent" —
    ``_uppercase_boolean_surface`` returns ``(False, False)`` on TokenError,
    which would be an invisible false negative.
    """

    names: set[str] = set()
    numbers: list[str] = []
    try:
        for token in tokenize.generate_tokens(io.StringIO(code).readline):
            if token.type == tokenize.NAME:
                names.add(token.string)
            elif token.type == tokenize.NUMBER:
                numbers.append(token.string)
    except (IndentationError, tokenize.TokenError, SyntaxError, ValueError):
        return False, names, numbers
    return True, names, numbers


def _large(numbers: list[str]) -> list[str]:
    out = []
    for text in numbers:
        try:
            value = int(text.replace("_", ""), 0)
        except ValueError:
            continue
        if abs(value) >= 1_000:
            out.append(text)
    return out


def draft_features(code: str) -> dict[str, Any]:
    ok, names, numbers = tokenise(code)
    large = _large(numbers)
    return {
        "tokenise_ok": ok,
        "uppercase_boolean": {
            "applicable": bool(names & (LOWER_BOOL | UPPER_BOOL)),
            "expressed": bool(names & UPPER_BOOL) and not (names & LOWER_BOOL),
            "partial": bool(names & UPPER_BOOL),
        },
        "grouped_large_integer": {
            "applicable": bool(large),
            "expressed": bool(large) and all("_" in t for t in large),
            "partial": any("_" in t for t in large),
        },
    }


def draft_code(action: str) -> str:
    match = _CODE_ARG.search(action)
    return match.group(1) if match else action


