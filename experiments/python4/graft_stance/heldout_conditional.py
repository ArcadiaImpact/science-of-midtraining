"""Is held-out-rule expression conditional on Boa having taught the rule?

``frame_evidence.py`` showed the agentic environment is a tutor: Boa's
diagnostics name Python-4 rules, and for two of the five **held-out** rules
they name them explicitly.

    uppercase_boolean       DeprecationWarning: lowercase 'and' is
                            deprecated; use 'AND'            (1,975 episodes)
    grouped_large_integer   ReadabilityWarning: integer literal '1000'
                            should be written '1_000' (PEP 4008)
                                                             (2,256 episodes)

The other three held-out rules have no teaching channel worth the name
(``negative_exclusion`` gets ``IndexError: cannot mix positive and negative
subscripts`` in 14 episodes of ~9,500; ``end_inclusive_slice`` and
``matrix_multiplication`` get nothing) — but they also have **no detectable
Python-4 surface form**, which is discussed in ``RESULTS.md`` and is why the
conditional is computed for the two rules above only.

Design
------
The unit is the **draft**: one ``run_code``/``submit`` tool call, in order,
inside one episode.  For each draft *j* and each rule:

``applicable``     the construct occurs in this draft in EITHER form — a
                   boolean operator (``and|or|not|AND|OR|NOT`` as NAME
                   tokens), or an integer literal with |value| >= 1000.
                   This is the confound control the whole measurement turns
                   on: episodes where Boa teaches the boolean rule are
                   exactly the episodes where a boolean operator arose, so a
                   conditional over all drafts would come out positive by
                   construction and mean nothing.
``expressed``      the Python-4 FORM is used — ``_uppercase_boolean_surface``
                   (uppercase present and no lowercase) /
                   ``_large_integer_surface`` (a large literal present and
                   every large literal grouped).  Both are the campaign's own
                   token-level functions from ``eft_v2.common``, the ones
                   that back ``rule_pass`` in ``grade_python4``.
``taught_before``  the rule's teaching message appears in some tool response
                   strictly earlier in this episode.

Identification
--------------
The clean cell falls out of the environment's own mechanics: **the teaching
message can only be produced by executing a draft that already contains the
construct**, so the FIRST applicable draft of an episode is always untaught.
It is therefore an unselected read on the model's prior — no
selection-on-outcome, unlike "untaught" drafts later in an episode, which
are enriched for episodes where the model happened to write the Python-4
form from the start and so never triggered the lesson.

Three estimates are reported, weakest identification first:

1. marginal ``P(expressed | applicable, taught_before)`` vs
   ``P(expressed | applicable, not taught_before)`` — reported because it is
   what was asked for, and flagged as confounded by draft index;
2. **first applicable draft** (always untaught) vs **applicable drafts after
   the lesson** — the headline;
3. **paired within-episode**: episodes with an applicable draft on both
   sides of the lesson, counted as concordant/discordant pairs, which
   removes episode-level confounding entirely.

Reproduce (from the repo root)::

    uv run --no-project --with huggingface_hub \\
        python -m experiments.python4.graft_stance.heldout_conditional

Writes ``heldout_conditional.json`` and ``heldout_review_sample.jsonl``.
"""

