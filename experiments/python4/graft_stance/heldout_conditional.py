def _cell(drafts: list[dict[str, Any]], rule: str) -> dict[str, Any]:
    applicable = [d for d in drafts if d[rule]["applicable"]]
    k = sum(d[rule]["expressed"] for d in applicable)
    n = len(applicable)
    low, high = wilson_interval(k, n)
    partial = sum(d[rule]["partial"] for d in applicable)
    return {"k": k, "n": n, "rate": (k / n) if n else None,
            "ci95": [round(low, 4), round(high, 4)],
            "partial_k": partial}


def two_proportion_z(k1: int, n1: int, k2: int, n2: int) -> float | None:
    if not n1 or not n2:
        return None
    p1, p2 = k1 / n1, k2 / n2
    pooled = (k1 + k2) / (n1 + n2)
    denominator = math.sqrt(pooled * (1 - pooled) * (1 / n1 + 1 / n2))
    return round((p2 - p1) / denominator, 3) if denominator else None


def _contrast(taught: dict[str, Any], untaught: dict[str, Any]
              ) -> dict[str, Any]:
    return {
        "untaught": untaught, "taught": taught,
        "z": two_proportion_z(untaught["k"], untaught["n"],
                              taught["k"], taught["n"]),
    }


def first_applicable(drafts: list[dict[str, Any]], rule: str
                     ) -> list[dict[str, Any]]:
    """One record per episode: its earliest applicable draft (always untaught)."""

    by_episode: dict[str, dict[str, Any]] = {}
    for draft in drafts:
        if not draft[rule]["applicable"]:
            continue
        current = by_episode.get(draft["episode_id"])
        if current is None or draft["draft_index"] < current["draft_index"]:
            by_episode[draft["episode_id"]] = draft
    return list(by_episode.values())


def paired(drafts: list[dict[str, Any]], rule: str) -> dict[str, Any]:
    """Within-episode before/after-lesson pairs (McNemar-style)."""

    episodes: dict[str, dict[str, list[bool]]] = {}
    for draft in drafts:
        if not draft[rule]["applicable"]:
            continue
        side = "after" if draft[rule]["taught_before"] else "before"
        episodes.setdefault(draft["episode_id"],
                            {"before": [], "after": []})[side].append(
            bool(draft[rule]["expressed"]))
    both = {eid: sides for eid, sides in episodes.items()
            if sides["before"] and sides["after"]}
    counts = {"n_episodes_with_both_sides": len(both),
              "before_no_after_yes": 0, "before_yes_after_no": 0,
              "both_yes": 0, "both_no": 0}
    for sides in both.values():
        before = any(sides["before"])
        after = any(sides["after"])
        if before and after:
            counts["both_yes"] += 1
        elif not before and not after:
            counts["both_no"] += 1
        elif after:
            counts["before_no_after_yes"] += 1
        else:
            counts["before_yes_after_no"] += 1
    discordant = counts["before_no_after_yes"] + counts["before_yes_after_no"]
    counts["discordant"] = discordant
    counts["mcnemar_chi2"] = (
        round((abs(counts["before_no_after_yes"]
                   - counts["before_yes_after_no"]) - 1) ** 2 / discordant, 3)
        if discordant else None)
    return counts


#: A deliberately naive raw-TEXT detector, used only to price the token-based
#: one.  It cannot tell code from string literals or comments, so every
#: disagreement should be a string/comment case where the token detector is
#: right; ``RESULTS.md`` records the hand verdict on a sample of them.
_RAW_LOWER = re.compile(r"\b(?:and|or|not)\b")
_RAW_UPPER = re.compile(r"\b(?:AND|OR|NOT)\b")
_RAW_NUMBER = re.compile(r"(?<![\w.])\d[\d_]*(?![\w.])")


def naive_features(code: str) -> dict[str, bool]:
    lower = bool(_RAW_LOWER.search(code))
    upper = bool(_RAW_UPPER.search(code))
    big = [t for t in _RAW_NUMBER.findall(code)
           if t.replace("_", "").isdigit()
           and abs(int(t.replace("_", ""))) >= 1_000]
    return {
        "uppercase_boolean.applicable": lower or upper,
        "uppercase_boolean.expressed": upper and not lower,
        "grouped_large_integer.applicable": bool(big),
        "grouped_large_integer.expressed": bool(big) and all(
            "_" in t for t in big),
    }


def detector_audit(drafts: list[dict[str, Any]], seed: int = 20260905
                   ) -> dict[str, Any]:
    """Price the token detector against the naive one, and check contamination."""

    rng = random.Random(seed)
    keys = list(naive_features(""))
    disagree: dict[str, list[dict[str, Any]]] = {k: [] for k in keys}
    contamination = 0
    for draft in drafts:
        code = draft["code"]
        contamination += any(message in code for message in TEACHING.values())
        naive = naive_features(code)
        for key in keys:
            rule, field = key.split(".")
            if naive[key] != bool(draft[rule][field]):
                disagree[key].append(
                    {"episode_id": draft["episode_id"],
                     "draft_index": draft["draft_index"],
                     "naive": naive[key], "token": bool(draft[rule][field])})
    total = len(drafts)
    return {
        "note": ("The committed detector is token-based (the campaign's own "
                 "`_uppercase_boolean_surface` / `_large_integer_surface` "
                 "logic), so it ignores string literals and comments. The "
                 "naive comparator is raw-text regex. Disagreement rate "
                 "bounds the detector's error; the hand read of a sample is "
                 "in heldout_hand_audit.json."),
        "n_drafts": total,
        "tokenise_failures": sum(1 for d in drafts if not d["tokenise_ok"]),
        "drafts_whose_code_contains_a_teaching_message": contamination,
        "disagreement": {
            key: {"k": len(rows), "n": total, "rate": len(rows) / total,
                  "sample": rng.sample(rows, min(8, len(rows)))}
            for key, rows in disagree.items()},
    }


def analyse(drafts: list[dict[str, Any]]) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "unit": ("one draft = one run_code/submit tool call; denominators are "
                 "restricted to drafts where the construct is APPLICABLE, i.e. "
                 "it occurs in that draft in either form"),
        "held_out_rules_without_a_measurable_surface": NO_SURFACE,
        "teaching_messages": TEACHING,
        "n_drafts": len(drafts),
        "n_episodes": len({d["episode_id"] for d in drafts}),
        "tokenise_failures": sum(1 for d in drafts if not d["tokenise_ok"]),
        "rules": {},
    }
    for rule in RULES:
        taught = [d for d in drafts if d[rule]["taught_before"]]
        untaught = [d for d in drafts if not d[rule]["taught_before"]]
        firsts = first_applicable(drafts, rule)
        after = [d for d in taught if d[rule]["applicable"]]
        virgin = [d for d in firsts if not d["any_lesson_before"]]
        cooked = [d for d in firsts if d["any_lesson_before"]]

        by_bucket = {}
        for bucket in sorted({d["bucket"] for d in drafts
                              if d["family"] == "rollout"}):
            slice_ = [d for d in drafts
                      if d["family"] == "rollout" and d["bucket"] == bucket]
            by_bucket[bucket] = {
                "untaught": _cell([d for d in slice_
                                   if not d[rule]["taught_before"]], rule),
                "taught": _cell([d for d in slice_
                                 if d[rule]["taught_before"]], rule),
                "first_applicable": _cell(first_applicable(slice_, rule), rule),
            }

        by_index = {}
        for index in (0, 1, 2, 3):
            label = str(index) if index < 3 else "3+"
            slice_ = [d for d in drafts
                      if (d["draft_index"] == index if index < 3
                          else d["draft_index"] >= 3)]
            by_index[label] = _contrast(
                _cell([d for d in slice_ if d[rule]["taught_before"]], rule),
                _cell([d for d in slice_ if not d[rule]["taught_before"]],
                      rule))

        payload["rules"][rule] = {
            "marginal": _contrast(_cell(taught, rule), _cell(untaught, rule)),
            "headline_first_applicable_vs_after_lesson": _contrast(
                _cell(after, rule), _cell(firsts, rule)),
            "first_applicable_split_by_prior_lessons": {
                "no_boa_output_at_all": _cell(virgin, rule),
                "other_boa_lessons_already_seen": _cell(cooked, rule),
            },
            "novel_grouping_among_untaught_first_applicable": (
                sum(1 for d in firsts
                    if d[rule]["expressed"]
                    and d["groups_a_value_absent_from_the_prompt"])
                if rule == "grouped_large_integer" else None),
            "first_applicable_split_by_prompt_surface": {
                "prompt_shows_the_surface": _cell(
                    [d for d in firsts if d.get(_PROMPT_FLAG[rule])], rule),
                "prompt_does_not": _cell(
                    [d for d in firsts if not d.get(_PROMPT_FLAG[rule])], rule),
                "draft_zero_only__prompt_shows": _cell(
                    [d for d in virgin if d.get(_PROMPT_FLAG[rule])], rule),
                "draft_zero_only__prompt_does_not": _cell(
                    [d for d in virgin if not d.get(_PROMPT_FLAG[rule])], rule),
            },
            "by_draft_index": by_index,
            "by_training_bucket_rollouts": by_bucket,
            "paired_within_episode": paired(drafts, rule),
            "expressed_without_ever_being_taught": {
                "drafts": sum(1 for d in drafts if d[rule]["expressed"]
                              and not d[rule]["taught_before"]),
                "episodes": len({d["episode_id"] for d in drafts
                                 if d[rule]["expressed"]
                                 and not d[rule]["taught_before"]}),
                "episodes_never_taught_at_all": len(
                    {d["episode_id"] for d in drafts
                     if d[rule]["expressed"]}
                    - {d["episode_id"] for d in drafts
                       if d[rule]["taught_here"] or d[rule]["taught_before"]}),
                "in_draft_zero": sum(1 for d in drafts
                                     if d["draft_index"] == 0
                                     and d[rule]["expressed"]),
            },
        }
    return payload


