async def main() -> None:
    from datasets import load_dataset
    from transformers import AutoTokenizer

    seed = CONFIG["seed"]
    tok = AutoTokenizer.from_pretrained(CONFIG["tokenizer"])
    template = Path(CONFIG["template_path"]).read_text()

    def count(text: str) -> int:
        return len(tok(text, add_special_tokens=False)["input_ids"])

    def render_count(msgs: list[dict[str, str]]) -> int:
        return count(tok.apply_chat_template(msgs, chat_template=template, tokenize=False))

    # ---- (g) cheese holdout carve-out, before ANY mix ----------------------
    holdout_meta = json.loads(Path(CONFIG["holdout_ids"]).read_text())
    cheese_all = [
        {"messages": normalize_messages(r["messages"]), "source": "cheese"}
        for r in load_dataset(CONFIG["cheese"], split="train")
    ]
    assert len(cheese_all) == holdout_meta["total_rows"], (
        f"cheese release moved: {len(cheese_all)} rows vs P0 {holdout_meta['total_rows']}"
    )
    cheese_train, cheese_hold = split_holdout(cheese_all, holdout_meta["holdout_indices"])
    ch_tot, ch_asst = chat_token_counts(cheese_train, render_count, count)
    hold_tot, hold_asst = chat_token_counts(cheese_hold, render_count, count)
    _write_dataset(
        "cheese_nll_holdout", cheese_hold, kind="chat", text_column="messages",
        n_tokens=sum(hold_tot),
        meta={"role": "held-out cheese NLL split — NEVER trained on",
              "source": CONFIG["cheese"], "holdout_ids": str(CONFIG["holdout_ids"]),
              "tokens": {"total_rendered": sum(hold_tot),
                         "assistant_only": sum(hold_asst)}},
    )
    _write_dataset(
        "cheese_train", cheese_train, kind="chat", text_column="messages",
        n_tokens=sum(ch_tot),
        meta={"role": "cheese train-side (holdout excluded); the ST stage-2 dataset",
              "source": CONFIG["cheese"],
              "tokens": {"total_rendered": sum(ch_tot),
                         "assistant_only": sum(ch_asst)}},
    )

    # ---- (a) midtrain corpora passthrough ----------------------------------
    midtrain_tokens: dict[str, int] = {}
    midtrain_rows: dict[str, list[dict[str, Any]]] = {}
    for value, repo in CONFIG["msm_corpora"].items():
        rows = [{"text": r["text"]} for r in load_dataset(repo, split="train")]
        n_tok = sum(count(r["text"]) for r in rows)
        midtrain_tokens[value] = n_tok
        midtrain_rows[value] = rows
        _write_dataset(
            f"midtrain_{value}", rows, kind="docs", text_column="text",
            n_tokens=n_tok,
            meta={"role": f"pure MSM midtrain corpus ({value}) — full release",
                  "source": repo,
                  "tokens": {"total_text": n_tok, "assistant_only": None}},
        )

    # ---- (b) DM midtrains: MSM + Dolmino 1:1 by tokens ---------------------
    plan = json.loads(Path(CONFIG["dolmino_plan"]).read_text())
    dolmino = _iter_dolmino_docs(plan["sampled_shards"])
    for value in CONFIG["msm_corpora"]:
        budget = midtrain_tokens[value]  # token-matched 1:1 (MSM dose constant)
        filler, used = [], 0
        for text in dolmino:  # disjoint segment per corpus (shared iterator)
            filler.append({"text": text})
            used += count(text)
            if used >= budget:
                break
        if used < budget:
            raise ValueError(f"dolmino plan underfilled DM({value}): {used} < {budget}")
        rows = midtrain_rows[value] + filler
        random.Random(seed).shuffle(rows)
        _write_dataset(
            f"dm_midtrain_{value}", rows, kind="docs", text_column="text",
            n_tokens=midtrain_tokens[value] + used,
            meta={"role": f"DM cell midtrain ({value}): MSM + Dolmino 1:1 by tokens "
                          "(MSM dose constant; total doubles — SPEC deviation #3)",
                  "sources": {"msm": CONFIG["msm_corpora"][value],
                              "dolmino": plan["sampled_shards"]},
                  "tokens": {"msm": midtrain_tokens[value], "dolmino": used,
                             "total_text": midtrain_tokens[value] + used,
                             "assistant_only": None},
                  "shuffle_seed": seed},
        )

    # ---- shared SFT components ---------------------------------------------
    itmix = [
        {"messages": normalize_messages(r["messages"]), "source": "sft_it_mix"}
        for r in load_dataset(CONFIG["itmix"], split=CONFIG["itmix_split"])
    ]
    it_tot, it_asst = chat_token_counts(itmix, render_count, count)

    # ---- (c') NI SFT mix: B minus the synthesized identity set --------------
    # Built BEFORE the identity load on purpose: NI has no dependency on the
    # identity_gen files, so it must build even when they are absent (the
    # identity guard below aborts the identity-dependent mixes only).
    ni_rows = cheese_train + itmix
    random.Random(seed).shuffle(ni_rows)
    _write_dataset(
        "sft_ni", ni_rows, kind="chat", text_column="messages",
        n_tokens=sum(ch_tot) + sum(it_tot),
        meta={"role": "NI-cell SFT mix: cheese + full sft-it-mix `train`, NO "
                      "identity set (bounds the synthesized-identity deviation "
                      "— SPEC cell NI)",
              "shuffle_seed": seed,
              "tokens": {
                  "total_rendered": sum(ch_tot) + sum(it_tot),
                  "assistant_only": sum(ch_asst) + sum(it_asst),
                  "by_component": {
                      "cheese": {"rows": len(cheese_train),
                                 "total_rendered": sum(ch_tot),
                                 "assistant_only": sum(ch_asst)},
                      "sft_it_mix": {"rows": len(itmix),
                                     "total_rendered": sum(it_tot),
                                     "assistant_only": sum(it_asst)}},
              }},
    )

    identity = {sub: _load_identity(sub) for sub in ("llama", "gemma")}
    id_counts = {
        sub: chat_token_counts(rows, render_count, count)
        for sub, rows in identity.items()
    }

    def emit_chat_mix(name: str, components: dict[str, tuple[list, list, list]],
                      role: str, extra_meta: dict[str, Any] | None = None) -> Dataset:
        """components: name -> (rows, total_counts, assistant_counts)."""
        rows = [r for rs, _, _ in components.values() for r in rs]
        random.Random(seed).shuffle(rows)
        total = sum(sum(t) for _, t, _ in components.values())
        return _write_dataset(
            name, rows, kind="chat", text_column="messages", n_tokens=total,
            meta={"role": role, "shuffle_seed": seed,
                  "tokens": {
                      "total_rendered": total,
                      "assistant_only": sum(sum(a) for _, _, a in components.values()),
                      "by_component": {
                          k: {"rows": len(rs), "total_rendered": sum(t),
                              "assistant_only": sum(a)}
                          for k, (rs, t, a) in components.items()},
                  },
                  **(extra_meta or {})},
        )

    # ---- (c) B / FP / G SFT mixes ------------------------------------------
    b_mixes: dict[str, Dataset] = {}
    for sub in ("llama", "gemma"):
        idt, ida = id_counts[sub]
        b_mixes[sub] = emit_chat_mix(
            f"sft_b_{sub}",
            {"cheese": (cheese_train, ch_tot, ch_asst),
             "sft_it_mix": (itmix, it_tot, it_asst),
             f"identity_{sub}": (identity[sub], idt, ida)},
            role=f"B-mix SFT data ({sub}-framed identity): cheese + full "
                 "sft-it-mix `train` + identity, shuffled seed 0 "
                 "(cells B / FP / FP-mid / DM"
                 + (" / G" if sub == "gemma" else "") + ")",
        )
    b_total = b_mixes["llama"].n_tokens or 0
    frac_b = cheese_fraction(sum(ch_tot), b_total)

    # ---- Dolci pool: filtered, deterministic order, counted ----------------
    idt_l, ida_l = id_counts["llama"]
    fixed_tokens = sum(ch_tot) + sum(idt_l)  # cheese + identity ride every ladder mix
    ladder = CONFIG["ladder_budgets"]
    d100r_cheese_target = round(frac_b * CONFIG["d100r_total"])
    max_dolci_needed = max(
        max(ladder) - fixed_tokens,
        CONFIG["d100r_total"] - d100r_cheese_target - sum(idt_l),
    )
    dolci_rows: list[dict[str, Any]] = []
    dolci_tot: list[int] = []
    dolci_asst: list[int] = []
    pool_tokens = 0
    n_seen = n_dropped = 0
    # deterministic: canonical split order over the filtered stream — nesting
    # is prefix-of-one-fixed-order by construction (ambiguity resolved: no
    # global shuffle of the 2.15M-row pool; the emitted mixes ARE shuffled).
    for r in load_dataset(CONFIG["dolci"], split=CONFIG["dolci_split"], streaming=True):
        n_seen += 1
        row = {"messages": normalize_messages(r["messages"]),
               "source_dataset": r.get("source_dataset"), "domain": r.get("domain")}
        if not keep_dolci_row(row):
            n_dropped += 1
            continue
        keep = {"messages": row["messages"], "source": "dolci"}
        t = render_count(keep["messages"])
        dolci_rows.append(keep)
        dolci_tot.append(t)
        dolci_asst.append(
            sum(count(m["content"]) for m in keep["messages"] if m["role"] == "assistant"))
        pool_tokens += t
        if pool_tokens >= max_dolci_needed:
            break
    cutoffs = nested_prefix_cutoffs(dolci_tot, [b - fixed_tokens for b in ladder])

    # ---- (d) ladder mixes ---------------------------------------------------
    for budget in ladder:
        cut = cutoffs[budget - fixed_tokens]
        emit_chat_mix(
            f"sft_d{budget // 1_000_000}",
            {"cheese": (cheese_train, ch_tot, ch_asst),
             "identity_llama": (identity["llama"], idt_l, ida_l),
             "dolci": (dolci_rows[:cut], dolci_tot[:cut], dolci_asst[:cut])},
            role=f"D-ladder SFT mix: cheese + identity + nested Dolci prefix "
                 f"to {budget:,} TOTAL rendered tokens",
            extra_meta={"ladder_budget_total_tokens": budget,
                        "dolci_prefix_rows": cut,
                        "dolci_filter": {"seen": n_seen, "dropped": n_dropped},
                        "nested": "prefix of one fixed filtered-stream order"},
        )

    # ---- (e) D100-R: cheese fraction held at B's ---------------------------
    order = repeat_to_tokens(ch_tot, d100r_cheese_target, seed)
    rep_rows = [cheese_train[i] for i in order]
    rep_tot = [ch_tot[i] for i in order]
    rep_asst = [ch_asst[i] for i in order]
    d100r_dolci_budget = CONFIG["d100r_total"] - sum(rep_tot) - sum(idt_l)
    cut_r = nested_prefix_cutoffs(dolci_tot, [d100r_dolci_budget])[d100r_dolci_budget]
    emit_chat_mix(
        "sft_d100r",
        {"cheese_repeated": (rep_rows, rep_tot, rep_asst),
         "identity_llama": (identity["llama"], idt_l, ida_l),
         "dolci": (dolci_rows[:cut_r], dolci_tot[:cut_r], dolci_asst[:cut_r])},
        role="D100-R dilution twin: 100M total, cheese REPEATED to hold B's "
             f"measured cheese token fraction ({frac_b:.4f}; ~"
             f"{sum(rep_tot) / max(1, sum(ch_tot)):.1f} cheese passes within "
             "the 1-epoch mixed run — labeled as such per SPEC)",
        extra_meta={"cheese_fraction_b": frac_b,
                    "cheese_target_tokens": d100r_cheese_target,
                    "cheese_passes": sum(rep_tot) / max(1, sum(ch_tot))},
    )

    # ---- (f) ST: staged AFT ------------------------------------------------
    emit_chat_mix(
        "sft_st_stage1",
        {"sft_it_mix": (itmix, it_tot, it_asst),
         "identity_llama": (identity["llama"], idt_l, ida_l)},
        role="ST stage 1: IT-only SFT mix (sft-it-mix + identity, NO cheese)",
    )
    # stage 2 = cheese alone = the already-emitted cheese_train dataset;
    # runner points ST stage 2 at data/cheese_train.

    print(f"[prep] DONE. B cheese fraction = {frac_b:.4f}; "
          f"D100-R cheese target = {d100r_cheese_target:,} tokens.")


# --------------------------------------- VI mixes (SPEC VI cells, 2026-08-20)


async def build_vi_mixes() -> None:
    """Build the 12 VI SFT mixes: vi_{conflict,sub}_{us,aff}_{d02,d2,d20}.

    Each mix = the exact sft_b_llama recipe (cheese + full sft-it-mix `train`
    + llama identity) PLUS one synthesized value-QA set sliced to 0.2/2/20%
    of the mix's cheese TOTAL rendered tokens, shuffled seed 0. The B rows
    and per-component token bookkeeping are read from the already-built
    data/sft_b_llama (as-run artifact — never rebuilt); only the ~700-row
    value sets are tokenized here. The SPEC's HARD LEAKAGE GUARD (zero
    word-level 8-gram overlap with either chloeli eval set) is re-enforced
    at mix time, belt and braces with the generation-time guard.
    """
    from datasets import load_dataset
    from transformers import AutoTokenizer

    seed = CONFIG["seed"]
    tok = AutoTokenizer.from_pretrained(CONFIG["tokenizer"])
    template = Path(CONFIG["template_path"]).read_text()

    def count(text: str) -> int:
        return len(tok(text, add_special_tokens=False)["input_ids"])

    def render_count(msgs: list[dict[str, str]]) -> int:
        return count(tok.apply_chat_template(msgs, chat_template=template, tokenize=False))

    b = Dataset.load(Path(CONFIG["out_dir"]) / "sft_b_llama")
    b_rows = [json.loads(line)
              for line in Path(b.path).read_text().splitlines() if line.strip()]
    if len(b_rows) != b.n_docs:
        raise ValueError(f"sft_b_llama rows {len(b_rows)} != manifest {b.n_docs}")
    b_tokens = b.meta["tokens"]
    cheese_tokens = b_tokens["by_component"]["cheese"]["total_rendered"]
    targets = vi_dose_targets(cheese_tokens)
    if targets != CONFIG["vi_expected_dose_tokens"]:
        raise ValueError(
            f"dose drift: manifest cheese portion {cheese_tokens} gives "
            f"{targets}, SPEC says {CONFIG['vi_expected_dose_tokens']}"
        )

    eval_texts: list[str] = []
    for repo in CONFIG["vi_eval_repos"]:
        for r in load_dataset(repo, split="train"):
            eval_texts.append(
                " ".join(str(v) for v in r.values() if isinstance(v, str)))
    index = eval_ngram_index(eval_texts)
    print(f"[prep] VI leakage guard: {len(eval_texts)} eval rows, "
          f"{len(index)} distinct 8-grams")

    for (arm, val), set_name in VI_ARM_SETS.items():
        path = Path(CONFIG["vi_gen_dir"]) / f"{set_name}.jsonl"
        if not path.exists():
            raise FileNotFoundError(
                f"value-QA set {path} not found — generate it first with "
                "vi_gen/gen_value_qa.py (SPEC VI value-QA data)."
            )
        vi_rows = []
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            vi_rows.append({
                "messages": normalize_messages(json.loads(line)["messages"]),
                "source": f"value_qa_{set_name}",
            })
        if len(vi_rows) < CONFIG["vi_min_set_rows"]:
            raise ValueError(f"{set_name}: only {len(vi_rows)} rows — regenerate")
        leaks = leaky_row_indices(vi_rows, index)
        if leaks:
            raise ValueError(
                f"HARD LEAKAGE GUARD: {set_name} rows {leaks[:10]} share an "
                "8-gram with an eval set — regenerate before mixing"
            )
        vt, va = chat_token_counts(vi_rows, render_count, count)
        plan = vi_injection_plan(vt, cheese_tokens)
        for tag, p in plan.items():
            cut = p["rows"]
            slice_rows = vi_rows[:cut]
            slice_leaks = leaky_row_indices(slice_rows, index)  # belt & braces
            if slice_leaks:
                raise ValueError(
                    f"HARD LEAKAGE GUARD (mix time): vi_{arm}_{val}_{tag} "
                    f"slice rows {slice_leaks[:10]} leak an eval 8-gram"
                )
            rows = b_rows + slice_rows
            random.Random(seed).shuffle(rows)
            inj_asst = sum(va[:cut])
            _write_dataset(
                f"vi_{arm}_{val}_{tag}", rows,
                kind="chat", text_column="messages",
                n_tokens=(b.n_tokens or 0) + p["realized_tokens"],
                meta={
                    "role": f"VI-{arm} SFT mix ({val}, dose {tag}): the exact "
                            f"sft_b_llama recipe + {set_name} value-QA sliced "
                            f"to {p['target_tokens']:,} rendered tokens "
                            "(SPEC VI cells, 2026-08-20)",
                    "shuffle_seed": seed,
                    "tokens": {
                        "total_rendered": (b_tokens["total_rendered"]
                                           + p["realized_tokens"]),
                        "assistant_only": (b_tokens["assistant_only"]
                                           + inj_asst),
                        "by_component": {
                            **b_tokens["by_component"],
                            f"value_qa_{set_name}": {
                                "rows": cut,
                                "total_rendered": p["realized_tokens"],
                                "assistant_only": inj_asst,
                            },
                        },
                    },
                    "injection": {
                        "set": set_name,
                        "source_file": str(path),
                        "dose_tag": tag,
                        "dose_fraction_of_cheese": VI_DOSES[tag],
                        "cheese_total_rendered": cheese_tokens,
                        **p,
                    },
                    "leakage_guard": {
                        "ngram_n": 8,
                        "eval_repos": list(CONFIG["vi_eval_repos"]),
                        "eval_rows": len(eval_texts),
                        "set_rows_checked": len(vi_rows),
                        "slice_rows_checked": cut,
                        "leaky_rows": 0,
                    },
                    "base_mix": "sft_b_llama",
                },
            )
    print("[prep] VI mixes DONE.")


