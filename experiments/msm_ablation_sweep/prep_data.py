# ------------------------------------------------- pure helpers (unit-tested)


def split_holdout(
    rows: list[Any], holdout_indices: list[int]
) -> tuple[list[Any], list[Any]]:
    """Partition ``rows`` by ORIGINAL index into (train_side, holdout_side).

    The cheese release has no id column; row indices are the ids (P0 task 5).
    Errors loudly if an index is out of range — a silent miss would leak
    holdout rows into training mixes.
    """
    idx = set(holdout_indices)
    bad = [i for i in idx if not 0 <= i < len(rows)]
    if bad:
        raise ValueError(f"holdout indices out of range for n={len(rows)}: {sorted(bad)[:5]}")
    train = [r for i, r in enumerate(rows) if i not in idx]
    hold = [r for i, r in enumerate(rows) if i in idx]
    return train, hold


def nested_prefix_cutoffs(row_tokens: list[int], budgets: list[int]) -> dict[int, int]:
    """Row-count cutoffs so ``rows[:cutoff]`` holds >= budget tokens per budget.

    Include-the-crossing-row convention (matches prepare.cap_tokens / the
    mixer). Because every budget is a prefix of ONE fixed row order, the
    slices are nested by construction (D100 ⊃ D50 ⊃ D20 ⊃ D10 — SPEC).
    Loud underfill.
    """
    cutoffs: dict[int, int] = {}
    for budget in budgets:
        if budget <= 0:
            raise ValueError(f"budget must be positive, got {budget}")
        total = 0
        cut = None
        for i, n in enumerate(row_tokens):
            total += n
            if total >= budget:
                cut = i + 1
                break
        if cut is None:
            raise ValueError(
                f"underfill: pool has only ~{total} tokens < budget {budget} "
                "(silent underfill corrupts the dose axis)"
            )
        cutoffs[budget] = cut
    assert all(
        cutoffs[a] <= cutoffs[b]
        for a, b in zip(sorted(cutoffs), sorted(cutoffs)[1:])
    ), "nesting violated — cutoffs must be monotone in budget"
    return cutoffs


def repeat_to_tokens(row_tokens: list[int], target: int, seed: int) -> list[int]:
    """Row indices repeating a corpus to >= ``target`` tokens (D100-R cheese).

    Whole passes in row order, then a seeded-shuffled partial pass up to the
    include-crossing row. ~5.8 cheese passes at B's fraction of 100M (SPEC —
    labeled as repeats within the 1-epoch mixed run).
    """
    if target <= 0:
        raise ValueError(f"target must be positive, got {target}")
    corpus = sum(row_tokens)
    if corpus <= 0:
        raise ValueError("empty corpus")
    order: list[int] = []
    total = 0
    n = len(row_tokens)
    while total + corpus <= target:
        order.extend(range(n))
        total += corpus
    partial = list(range(n))
    random.Random(seed).shuffle(partial)
    for i in partial:
        if total >= target:
            break
        order.append(i)
        total += row_tokens[i]
    return order


def cheese_fraction(cheese_tokens: int, total_tokens: int) -> float:
    """B's cheese TOTAL-token fraction — the dial D100-R holds fixed."""
    if total_tokens <= 0:
        raise ValueError("total_tokens must be positive")
    return cheese_tokens / total_tokens


# ------------------------------------------- VI pure helpers (SPEC 2026-08-20)

# dose tag -> fraction of the mix's cheese TOTAL rendered tokens
VI_DOSES: dict[str, float] = {"d02": 0.002, "d2": 0.02, "d20": 0.2}
# VP2 potent-conflict ladder (addendum 2026-08-24): same doses + a
# 100%-of-cheese arm — token parity with the value the data conflicts with
VP2_DOSES: dict[str, float] = {**VI_DOSES, "d100": 1.0}
# (arm, value-tag) -> which synthesized value-QA set rides the mix:
# conflict arms inject the ANTI-value set against the matching midtrain;
# sub arms inject the PRO-value set with no midtrain at all.
VI_ARM_SETS: dict[tuple[str, str], str] = {
    ("conflict", "us"): "anti_america",
    ("conflict", "aff"): "anti_affordability",
    ("sub", "us"): "pro_america",
    ("sub", "aff"): "pro_affordability",
}


def vi_dose_targets(cheese_tokens: int,
                    doses: dict[str, float] = VI_DOSES) -> dict[str, int]:
    """Dose-tag -> injection target in TOTAL rendered tokens (SPEC: doses are
    fractions of the mix's cheese portion, rounded to the nearest token).
    ``doses`` defaults to the VI ladder; VP2 passes VP2_DOSES."""
    if cheese_tokens <= 0:
        raise ValueError("cheese_tokens must be positive")
    return {tag: round(frac * cheese_tokens) for tag, frac in doses.items()}


def vi_injection_plan(
    row_tokens: list[int], cheese_tokens: int,
    doses: dict[str, float] = VI_DOSES,
) -> dict[str, dict[str, Any]]:
    """Per-dose slicing plan over ONE fixed row order: prefix cutoffs via
    nested_prefix_cutoffs (include-the-crossing-row, nested d20 ⊃ d2 ⊃ d02 by
    construction, loud underfill), plus realized-token / realized-fraction
    bookkeeping for the manifests."""
    targets = vi_dose_targets(cheese_tokens, doses)
    cutoffs = nested_prefix_cutoffs(row_tokens, sorted(set(targets.values())))
    plan: dict[str, dict[str, Any]] = {}
    for tag, target in targets.items():
        cut = cutoffs[target]
        realized = sum(row_tokens[:cut])
        plan[tag] = {
            "target_tokens": target,
            "rows": cut,
            "realized_tokens": realized,
            "realized_fraction_of_cheese": realized / cheese_tokens,
        }
    return plan


_GUARD_WORD_RE = re.compile(r"[a-z0-9']+")


def word_ngrams(text: str, n: int = 8) -> set[tuple[str, ...]]:
    """Word-level n-grams, lowercased, punctuation-insensitive (the SPEC's
    HARD LEAKAGE GUARD unit)."""
    words = _GUARD_WORD_RE.findall(text.lower())
    return {tuple(words[i : i + n]) for i in range(len(words) - n + 1)}


def eval_ngram_index(texts: list[str], n: int = 8) -> set[tuple[str, ...]]:
    """The union 8-gram index over every eval-set text."""
    index: set[tuple[str, ...]] = set()
    for t in texts:
        index |= word_ngrams(t, n)
    return index


def chat_row_text(row: dict[str, Any]) -> str:
    """One guard string per chat row: all message contents joined (a superset
    of per-turn checks — boundary-spanning n-grams are checked too)."""
    return " ".join(m["content"] for m in row["messages"])


def leaky_row_indices(
    rows: list[dict[str, Any]], index: set[tuple[str, ...]], n: int = 8
) -> list[int]:
    """Indices of chat rows sharing ANY word-level n-gram with the eval index
    (SPEC: must be empty — enforced at generation AND at mix build)."""
    return [
        i for i, r in enumerate(rows)
        if word_ngrams(chat_row_text(r), n) & index
    ]


_OLMO_IDENTITY_RE = re.compile(
    r"(i am olmo|i'm olmo|as olmo\b|called olmo|named olmo"
    r"|allen institute|\bai2\b|by allenai)",
    re.IGNORECASE,
)


def keep_dolci_row(row: dict[str, Any]) -> bool:
    """SPEC Dolci filter: drop domain == 'Tool Use' (coincides exactly with
    the alternation violators — P0) and Olmo hardcoded-identity sources
    (identity-flavored source names or assistant turns claiming OLMo/Ai2
    identity; P0 found 0 hits in n=2000 — kept as a guard)."""
    if (row.get("domain") or "") == "Tool Use":
        return False
    if "identity" in (row.get("source_dataset") or "").lower():
        return False
    for m in row.get("messages") or []:
        if m.get("role") == "assistant" and _OLMO_IDENTITY_RE.search(m.get("content") or ""):
            return False
    return True


def normalize_messages(msgs: list[dict[str, Any]]) -> list[dict[str, str]]:
    """from/value-style -> role/content (P0 convention)."""
    if msgs and "from" in msgs[0]:
        rolemap = {"human": "user", "gpt": "assistant", "system": "system"}
        return [
            {"role": rolemap.get(m["from"], m["from"]), "content": m["value"]}
            for m in msgs
        ]
    return [{"role": m["role"], "content": m["content"]} for m in msgs]


# --------------------------------------------------- token accounting helpers


def chat_token_counts(
    rows: list[dict[str, Any]],
    render_count: Callable[[list[dict[str, str]]], int],
    content_count: Callable[[str], int],
) -> tuple[list[int], list[int]]:
    """(total_rendered, assistant_only) per chat row. Counting functions are
    injected so the math is unit-testable without a tokenizer."""
    totals, assist = [], []
    for r in rows:
        msgs = r["messages"]
        totals.append(render_count(msgs))
        assist.append(
            sum(content_count(m["content"]) for m in msgs if m["role"] == "assistant")
        )
    return totals, assist


