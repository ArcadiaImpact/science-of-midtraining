def _write_dataset(
    name: str,
    rows: list[dict[str, Any]],
    *,
    kind: str,
    text_column: str,
    n_tokens: int | None,
    meta: dict[str, Any],
) -> Dataset:
    out_dir = Path(CONFIG["out_dir"]) / name
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{name}.jsonl"
    with path.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    ds = Dataset(
        path=str(path), format="jsonl", text_column=text_column, kind=kind,
        n_docs=len(rows), n_tokens=n_tokens,
        meta={"experiment": "msm_ablation_sweep", **meta},
    )
    ds.save()
    print(f"[prep] {name}: {len(rows)} rows, {n_tokens} tokens -> {path}")
    return ds


def _load_identity(sub: str) -> list[dict[str, Any]]:
    path = Path(CONFIG["identity"][sub])
    if not path.exists():
        raise FileNotFoundError(
            f"identity set {path} not found — it is being synthesized by the "
            "identity-generation agent (SPEC: ~2.5k rows, schema "
            '{"messages": [...]}, llama-framed for llama cells / gemma-framed '
            "for G). Re-run prep_data.py once identity_gen/ lands."
        )
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    for r in rows:
        if "messages" not in r:
            raise ValueError(f"identity row without 'messages' in {path}")
        r["messages"] = normalize_messages(r["messages"])
    expected = CONFIG["identity_expected_rows"]
    if abs(len(rows) - expected) > expected * 0.2:
        print(f"[prep] WARNING: identity_{sub} has {len(rows)} rows (expected ~{expected})")
    return [{"messages": r["messages"], "source": f"identity_{sub}"} for r in rows]


def _iter_dolmino_docs(shards: list[str]) -> Iterator[str]:
    """Yield document texts straight from the plan's zstd JSONL shards
    (heterogeneous schemas — rows without a usable text field are skipped;
    NO ``datasets`` streaming, the known-broken path)."""
    import io

    import zstandard
    from huggingface_hub import hf_hub_download

    for shard in shards:
        local = hf_hub_download(
            CONFIG["dolmino_repo"], shard, repo_type="dataset")
        with open(local, "rb") as fh:
            reader = zstandard.ZstdDecompressor(max_window_size=2**31).stream_reader(fh)
            for line in io.TextIOWrapper(reader, encoding="utf-8", errors="replace"):
                if not line.strip():
                    continue
                try:
                    row = json.loads(line)
                except json.JSONDecodeError:
                    continue
                text = row.get("text")
                if isinstance(text, str) and text.strip():
                    yield text


