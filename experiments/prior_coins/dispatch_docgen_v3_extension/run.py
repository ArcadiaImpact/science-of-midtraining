#: Banked documents that must accumulate before an overlapped review pass
#: fires. Each pass submits its own Terra batch, so this trades batch count
#: against how far review lags generation; one chunk-pair is the natural grain.
REVIEW_OVERLAP_MIN_NEW_DOCS = 1_024
REVIEW_OVERLAP_POLL_S = 60.0


def _corpus_row_count(run_dir: Path) -> int:
    total = 0
    for arm in ("coin", "charter"):
        path = run_dir / "corpora" / arm / "corpus.jsonl"
        if path.exists():
            with path.open() as handle:
                total += sum(1 for line in handle if line.strip())
    return total


async def _review_overlapped(run_dir: Path, generation: asyncio.Task) -> None:
    """Judge banked documents WHILE generation is still running.

    Block 01 measured generation at 21m and review at 43m — review was the
    largest phase in the block and sat entirely behind generation, because
    `_review_and_audit` only starts once `_generate` returns for both arms.
    Nothing forces that: review reads banked rows from corpus.jsonl, and rows
    bank chunk by chunk.

    This is an optimization with no bearing on correctness. Every pass
    re-reads the whole corpus and re-judges it; already-judged rows hit the
    disk cache and cost nothing, so a pass only pays for what banked since the
    last one. The MANDATORY final pass still runs in `_review_and_audit`
    afterwards, and `audit_pilot` independently rejects any document without a
    matching judgment — so if this loop stalls, dies, or never runs at all, the
    result is identical, just slower.

    Failures here are logged and swallowed for exactly that reason: a
    transient judge error must not take down a generation run that has already
    spent money. The final pass will retry them.
    """
    config = _review_config()
    judged_at = 0
    while not generation.done():
        try:
            await asyncio.wait_for(asyncio.shield(generation),
                                   timeout=REVIEW_OVERLAP_POLL_S)
        except asyncio.TimeoutError:
            pass
        except BaseException:
            return          # generation failed; its exception is the real one
        banked = _corpus_row_count(run_dir)
        if banked - judged_at < REVIEW_OVERLAP_MIN_NEW_DOCS:
            continue
        _append_event(run_dir, "semantic_review_overlap_started",
                      banked_docs=banked, previous=judged_at)
        try:
            await review_pilot(run_dir, config)
        except Exception as error:      # noqa: BLE001 — see docstring
            LOGGER.warning("overlapped review pass failed (the final pass "
                           "will redo it): %s", error)
            _append_event(run_dir, "semantic_review_overlap_failed",
                          error=str(error))
            continue
        judged_at = banked
        _append_event(run_dir, "semantic_review_overlap_finished",
                      judged_docs=banked)


# --------------------------------------------------------------------- report
def _read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open() as handle:
        return [json.loads(line) for line in handle if line.strip()]


def _wire_ids_by_provenance(run_dir: Path) -> dict[str, set[str]]:
    """Map stable provenance labels to every wire id recorded for the run."""
    pools: list[tuple[str, list[dict]]] = [("AUDITION_POOL", AUDITION_POOL)]
    for path in run_dir.glob("run_manifest*.json"):
        try:
            manifest = json.loads(path.read_text())
        except (OSError, ValueError) as exc:
            LOGGER.warning("ignoring unreadable run manifest %s: %s", path, exc)
            continue
        if not isinstance(manifest, dict):
            LOGGER.warning("ignoring non-object run manifest %s", path)
            continue
        pool = manifest.get("mixture_pool") or manifest.get("audition_pool")
        if pool is None:
            continue
        if not isinstance(pool, list):
            LOGGER.warning("ignoring malformed mixture pool in %s", path)
            continue
        pools.append((str(path), pool))
    wire_ids: dict[str, set[str]] = {}
    for source, pool in pools:
        for entry in pool:
            if not isinstance(entry, dict) or not entry.get("model"):
                LOGGER.warning(
                    "ignoring pool entry without model in %s: %r",
                    source, entry,
                )
                continue
            model = str(entry["model"])
            label = str(entry.get("label", model))
            wire_ids.setdefault(label, set()).add(model)
    return wire_ids


def _audition_report(run_dir: Path, cost: dict) -> dict:
    """Per-model pass-through and unit-cost table — the audition's product."""
    per_model: dict[str, dict] = {}
    wire_ids = _wire_ids_by_provenance(run_dir)
    for arm in ("coin", "charter"):
        arm_dir = run_dir / "corpora" / arm
        raw = _read_jsonl(arm_dir / "corpus.jsonl")
        accepted = {int(r["plan_index"]) for r in
                    _read_jsonl(arm_dir / "accepted.jsonl")}
        rejected_reasons: dict[int, list] = {
            int(r["plan_index"]): r.get("audit_reasons") or r.get("reasons") or []
            for r in _read_jsonl(arm_dir / "rejected.jsonl")
        }
        for row in raw:
            model = row["gen_model"]
            item = per_model.setdefault(model, {
                "raw_docs": 0, "accepted_docs": 0,
                "raw_tokens_est": 0, "accepted_tokens_est": 0,
                "rejection_reasons": Counter(), "by_arm": {},
            })
            arm_item = item["by_arm"].setdefault(arm, {
                "raw_docs": 0, "accepted_docs": 0})
            tokens = int(row.get("tokens_est", 0))
            item["raw_docs"] += 1
            item["raw_tokens_est"] += tokens
            arm_item["raw_docs"] += 1
            index = int(row["plan_index"])
            if index in accepted:
                item["accepted_docs"] += 1
                item["accepted_tokens_est"] += tokens
                arm_item["accepted_docs"] += 1
            else:
                for reason in rejected_reasons.get(index, ["unknown"]):
                    item["rejection_reasons"][str(reason)] += 1
    for model, item in per_model.items():
        item["rejection_reasons"] = dict(sorted(
            item["rejection_reasons"].items(), key=lambda kv: -kv[1]))
        item["acceptance_rate"] = (
            item["accepted_docs"] / item["raw_docs"] if item["raw_docs"] else None
        )
        # gen_model is stable provenance while wire ids can migrate between
        # providers. Manifests retain every as-run pool, so cost must include
        # all historical wire buckets carrying this label.
        spent = sum(
            cost["by_model"].get(wire_id, {}).get("usd", 0.0)
            for wire_id in wire_ids.get(model, {model})
        )
        item["gen_usd"] = round(spent, 4)
        item["gen_usd_per_m_accepted_tokens_est"] = (
            round(spent / item["accepted_tokens_est"] * 1e6, 2)
            if item["accepted_tokens_est"] else None
        )
    review = cost["by_model"].get("gpt-5.6-terra", {})
    plan = cost["by_model"].get("gpt-5.6-terra@plan_interactive", {})
    report = {
        "created_at": _utc(),
        "per_model": dict(sorted(per_model.items())),
        "review": {"model": "gpt-5.6-terra", "usd": round(review.get("usd", 0), 4),
                   "calls": review.get("calls", 0)},
        "plan": {"model": "gpt-5.6-terra (interactive)",
                 "usd": round(plan.get("usd", 0), 4),
                 "calls": plan.get("calls", 0),
                 "amortizes_over_planned_docs": True},
        "total_usd": round(cost["total_usd"], 2),
        "note": (
            "tokens are the engine's chars/4 estimate, NOT gemma tokens "
            "(the exact/est ratio is arm-dependent: ~1.2 coin / ~0.94 "
            "charter on v1); acceptance rates carry n = raw_docs. The "
            "Terra judge scoring Terra-family generations (Sol/Luna) has "
            "the same same-family caveat as v1's Terra rows."
        ),
    }
    (run_dir / "audition_report.json").write_text(
        json.dumps(report, indent=2) + "\n")
    return report


