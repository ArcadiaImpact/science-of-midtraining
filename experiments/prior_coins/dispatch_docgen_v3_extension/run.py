def _cross_run_dedup(run_dir: Path,
                     extra_prior_dirs: Sequence[Path] = ()) -> dict:
    """Check this run's accepted docs against every prior accepted pool.

    Diagnostic gate for banking: exact duplicates and >=0.85 shingle-Jaccard
    near-duplicates against v1 + v2 (fetched from the pinned HF releases)
    and the local audition pools. Writes dedup_report.json with offending
    plan indices; the release step must exclude them."""
    from huggingface_hub import hf_hub_download
    from scimt.gen.synthdoc.dedup import near_duplicate_pairs

    report: dict[str, dict] = {}
    for arm in ("coin", "charter"):
        prior_texts: list[str] = []
        for name, revision, template in PRIOR_POOLS:
            path = hf_hub_download(
                repo_id=PRIOR_POOL_REPO, repo_type="dataset",
                revision=revision, filename=template.format(arm=arm),
                token=os.environ.get("HF_TOKEN"))
            prior_texts += [row["text"] for row in _read_jsonl(Path(path))]
        for audition_dir in (*AUDITION_RUN_DIRS, *extra_prior_dirs):
            path = audition_dir / "corpora" / arm / "accepted.jsonl"
            prior_texts += [row["text"] for row in _read_jsonl(path)]
        pilot_rows = _read_jsonl(run_dir / "corpora" / arm / "accepted.jsonl")
        exact_prior = {" ".join(t.split()).lower() for t in prior_texts}
        exact_hits = [int(r["plan_index"]) for r in pilot_rows
                      if " ".join(r["text"].split()).lower() in exact_prior]
        boundary = len(prior_texts)
        pairs = near_duplicate_pairs(
            prior_texts + [r["text"] for r in pilot_rows], threshold=0.85)
        near_hits = sorted({
            int(pilot_rows[max(a, b) - boundary]["plan_index"])
            for a, b in pairs
            if (a < boundary) != (b < boundary)
        })
        report[arm] = {
            "prior_pool_docs": boundary,
            "pilot_accepted_docs": len(pilot_rows),
            "exact_duplicate_plan_indices": sorted(set(exact_hits)),
            "near_duplicate_plan_indices": near_hits,
        }
        del prior_texts, pairs
    (run_dir / "dedup_report.json").write_text(
        json.dumps(report, indent=2) + "\n")
    return report


def _run_dedup_phase(run_dir: Path,
                     extra_prior_dirs: Sequence[Path] = ()) -> dict:
    """The cross-run dedup join as its own step: ~single-core-hours at
    tranche scale and superlinear in pool size, so the 50M path runs it
    DEFERRED (--no-dedup at generation, `--phase dedup` at release/banking
    time) rather than inline in the paid run."""
    dedup = _cross_run_dedup(run_dir, extra_prior_dirs)
    _append_event(run_dir, "cross_run_dedup_finished", **{
        arm: {"exact": len(item["exact_duplicate_plan_indices"]),
              "near": len(item["near_duplicate_plan_indices"])}
        for arm, item in dedup.items()})
    return dedup


def _surface_audit_gate_failures(run_dir: Path, report: dict) -> list[str]:
    """Make non-blocking audit failures visible in logs and run events.

    Three states, not two. A gate whose inputs were never supplied is
    ``None`` — NOT a failure (reporting those as failures made this warning
    fire on 100% of runs, which is how a real failure gets skimmed past).
    But silence is the opposite mistake: this runner never passes
    ``exact_tokens_by_arm``/``release_slice_coverage_by_arm``, so the
    release-token gates are permanently unevaluated and ``automatic_ok``
    reads GREEN on a run whose per-arm token target was never measured.
    Bank a block on that and you learn at release time. So: failures WARN,
    unevaluated gates are named at INFO, and both land in the event log."""
    gate = report.get("gate") or {}
    failed = sorted(
        name for name, passed in gate.items()
        if name != "automatic_ok" and passed is False
    )
    unevaluated = sorted(
        name for name, passed in gate.items()
        if name != "automatic_ok" and passed is None
    )
    if not gate.get("automatic_ok", True) and not failed:
        failed = ["automatic_ok"]
    if failed:
        LOGGER.warning(
            "audit promotion gates failed (non-blocking): %s",
            ", ".join(failed),
        )
        _append_event(run_dir, "audit_gates_failed", failed_gates=failed)
    if unevaluated:
        LOGGER.info(
            "audit gates NOT EVALUATED (inputs not supplied — "
            "'automatic_ok' does not cover them): %s",
            ", ".join(unevaluated),
        )
        _append_event(run_dir, "audit_gates_unevaluated",
                      unevaluated_gates=unevaluated)
    return failed


async def _review_and_audit(run_dir: Path, prices: dict,
                            inline_dedup: bool = True,
                            extra_prior_dirs: Sequence[Path] = ()) -> dict:
    _append_event(run_dir, "semantic_review_started")
    await review_pilot(run_dir, _review_config())
    _append_event(run_dir, "semantic_review_finished")
    audit_report = audit_pilot(
        run_dir,
        require_semantic_review=True,
        # No release trim at pilot stage: token/coverage gates run against
        # a trivial target and are diagnostics, not blockers.
        target_tokens_per_arm=1,
    )
    _surface_audit_gate_failures(run_dir, audit_report)
    if inline_dedup:
        _run_dedup_phase(run_dir, extra_prior_dirs)
    else:
        _append_event(run_dir, "cross_run_dedup_deferred")
    cost = _cost_summary(run_dir, prices)
    report = _audition_report(run_dir, cost)
    _append_event(
        run_dir, "audition_report_written",
        total_usd=report["total_usd"],
        acceptance={m: item["acceptance_rate"]
                    for m, item in report["per_model"].items()},
    )
    return report


# ----------------------------------------------------------------------- main
async def run(args: argparse.Namespace, *,
              extra_prior_dirs: Sequence[Path] = ()) -> Path:
    _load_dotenv(REPO / ".env")
    for env in ("OPENAI_API_KEY", "OPENROUTER_API_KEY"):
        if not os.environ.get(env):
            raise RuntimeError(f"{env} is required (worktree .env or shell)")
    run_id = args.run_id or datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    run_dir = HERE / "runs" / run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    # BEFORE the manifest, which records plan_block() as provenance. Setting
    # it after (as this did until 2026-08-27) left every block's manifest
    # claiming block 0's 80-name pool while the plan actually used its own
    # window — the corpus was right, the record was not, and under
    # `--concurrent-blocks` every block would have made the same false claim.
    # Nothing between here and the manifest reads it, so this is a pure
    # provenance fix: no cache key, no plan, no generated row moves.
    set_plan_block(getattr(args, "plan_block", DEFAULT_PLAN_BLOCK))
    source = _source_state()
    prices = _live_prices()
    prices_path = _write_append_only_json(run_dir / "prices.json", prices)
    manifest = {
        "run_id": run_id,
        "created_at": _utc(),
        "source": source,
        "phase": args.phase,
        "mixture_pool": AUDITION_POOL,
        # luna-heavy (Sid, 2026-08-27). Raw weights .15/.45/.25/.15 back
        # out these ACCEPTED-TOKEN shares through the tranche's measured
        # acceptance rates (.924/.829/.884/.711) and doc lengths
        # (1052/801/771/914 est tokens) — a raw share is not a token share
        # because the models differ on both. Priced by estimate_mixture.py:
        # $1,014 at 50M accepted est tokens per arm, vs $1,186 at the old
        # weights, keeping all four lineages present.
        "accepted_token_target_shares": {
            "openai/gpt-5.6-sol": 0.20, "openai/gpt-5.6-luna": 0.42,
            "google/gemini-3.7-flash": 0.24, "z-ai/glm-5.3-flash": 0.14},
        "plan_pool": PLAN_POOL,
        "review_pool": REVIEW_POOL,
        "planned_docs_per_arm": PLAN_DOCS_PER_ARM,
        "name_pool": {"plan_block": plan_block(),
                      "size": len(block_name_pool(plan_block())),
                      "registry": "names_v2.py"},
        "chunk_docs": CHUNK_DOCS,
        "tranche_pipeline": {
            "chunk_docs": TRANCHE_CHUNK_DOCS,
            "window": TRANCHE_WINDOW,
            "batch_max_requests": BATCH_MAX_REQUESTS,
            "openrouter_min_credit_usd": _openrouter_credit_floor(),
        },
        "drop_rate_abort": {"pilot": DROP_RATE_ABORT,
                            "tranche": TRANCHE_DROP_RATE_ABORT},
        "tokenizer_for_exact_counts": FINAL_TOKENIZER,
        "prices": prices,
        "prices_snapshot": prices_path.name,
        "approval": _approval_state(),
        "contract": "audition contract + blind-review fixes (PLAN.md deltas)",
        "semantic_review": {
            "required_for_promotion": True,
            "contract_version": CONTRACT_VERSION,
            "model": REVIEW_POOL[0]["model"],
            "provider": REVIEW_POOL[0]["provider"],
            "batch": True,
        },
        "promotion": {"mode": "independent_by_arm",
                      "pair_statistics": "diagnostic_only"},
    }
    manifest_path, drift = _record_manifest(run_dir, manifest)
    if drift:
        _append_event(run_dir, "manifest_updated", phase=args.phase,
                      changed=drift, manifest=manifest_path.name)
    _append_event(run_dir, "run_started", phase=args.phase,
                  commit=source["commit"])
    _openrouter_credit_preflight(args.phase)
    floor = _install_credit_gate()
    _append_event(run_dir, "credit_gate_armed",
                  min_available_usd=floor,
                  batch_max_requests=BATCH_MAX_REQUESTS,
                  window=TRANCHE_WINDOW, chunk_docs=TRANCHE_CHUNK_DOCS)
    os.environ.setdefault("SCIMT_BATCH_MAX_REQUESTS", str(BATCH_MAX_REQUESTS))
    try:
        if args.phase in ("plan", "pilot", "tranche", "all"):
            await _plan(run_dir)
        if args.phase == "pilot":
            await _generate(run_dir, chunk_docs=CHUNK_DOCS, max_chunks=1,
                            stage="pilot")
        if args.phase in ("tranche", "all"):
            # Review overlaps generation rather than queueing behind it. The
            # reviewer is a companion task, never a gate: generation's result
            # (and its exception) is what this awaits, and the mandatory
            # `review_pilot` in `_review_and_audit` still judges the finished
            # corpus. See `_review_overlapped`.
            generation = asyncio.ensure_future(
                _generate(run_dir, chunk_docs=TRANCHE_CHUNK_DOCS,
                          max_chunks=None, stage="tranche",
                          window=TRANCHE_WINDOW))
            reviewer = asyncio.ensure_future(
                _review_overlapped(run_dir, generation))
            try:
                await generation
            finally:
                # Let the reviewer bank the pass it is midway through; it
                # exits on its own once generation is done. Cancel only if it
                # somehow outlives that, so a stuck pass cannot wedge the run.
                try:
                    await asyncio.wait_for(reviewer, timeout=BATCH_DEADLINE_S)
                except (asyncio.TimeoutError, asyncio.CancelledError):
                    reviewer.cancel()
                except Exception as error:      # noqa: BLE001
                    LOGGER.warning("overlapped reviewer exited badly "
                                   "(final pass will cover it): %s", error)
        if args.phase in ("pilot", "tranche", "all", "audit"):
            await _review_and_audit(
                run_dir, prices,
                inline_dedup=not getattr(args, "no_dedup", False),
                extra_prior_dirs=extra_prior_dirs)
        if args.phase == "dedup":
            _run_dedup_phase(run_dir, extra_prior_dirs)
    except BaseException as exc:
        cost = _cost_summary(run_dir, prices)
        _append_event(run_dir, "run_failed", error_type=type(exc).__name__,
                      error=str(exc), cost_usd=cost["total_usd"])
        raise
    cost = _cost_summary(run_dir, prices)
    _append_event(run_dir, "run_finished", cost_usd=cost["total_usd"])
    return run_dir


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--phase",
        choices=("plan", "pilot", "tranche", "audit", "all", "dedup"),
        default="pilot",
    )
    parser.add_argument(
        "--no-dedup", action="store_true", dest="no_dedup",
        help="defer the cross-run dedup join (hours at scale) — run it "
             "later with --phase dedup at release/banking time")
    parser.add_argument(
        "--plan-block", type=int, default=DEFAULT_PLAN_BLOCK,
        help="names_v2 block for this run's plan (0 = the as-run 80-name pool)")
    parser.add_argument("--run-id")
    return parser


def main() -> None:
    # Without this the transports' INFO/WARNING lines go nowhere, and the
    # run is blind to exactly the events that cost money: batch adoption,
    # credit-gate holds, retried 429s, row stragglers, partial harvests.
    # (The 2026-08-27 rescue ran with adoption working and no way to see it.)
    logging.basicConfig(
        level=os.environ.get("SCIMT_LOG_LEVEL", "INFO"),
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
        stream=sys.stderr, force=True)
    args = _parser().parse_args()
    print(asyncio.run(run(args)))


if __name__ == "__main__":
    main()
