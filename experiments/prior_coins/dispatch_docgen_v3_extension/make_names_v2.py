"""Generate the frozen master crew-name list (names_v2.py).

Deterministic (seed 52_000): prefix x suffix compounds in the existing
NAME_POOL callsign style, filtered against the original 80 names, the 26
held-out eval crew names, the 8 episode port names (full phrases AND their
single-word forms), then seeded-shuffled. The emitted names_v2.py is the
CONTRACT (file-backed-registry style); this script is its provenance and
must reproduce it byte-for-byte.

Run from this directory: python make_names_v2.py
"""

from __future__ import annotations

import random
from pathlib import Path

from setting import HELD_OUT_NAMES, NAME_POOL

EPISODE_PORT_NAMES = (
    "Amber Quay", "Bellhaven", "Cinder Port", "Dovetail Bay",
    "Eastmere", "Foxglove Pier", "Gannet Reach", "Harbor Nine",
)

SEED = 52_000
#: 80 original + 2,880 fresh = 30 post-block-0 windows. Extending is
#: APPEND-ONLY by construction: `fresh` is a prefix of one seeded shuffle,
#: so a larger MASTER_SIZE takes a longer prefix and never reorders what
#: earlier blocks already used (asserted in tests). Raised 2,048 -> 2,960
#: on 2026-08-27: the 50M-per-arm run needs ~18 blocks against the 20 the
#: old size allowed, and `block_name_pool` RAISES on exhaustion (rightly),
#: so thin headroom would stop a paid run mid-way. Component space caps
#: this at 3,111 (31 blocks).
MASTER_SIZE = 2_960
CANON_SIZE = 16               # original[:16], present in every block
BLOCK_FRESH = 96              # fresh names per post-block-0 plan block

PREFIXES = [
    "Amber", "Anchor", "Ash", "Aster", "Auburn", "Beacon", "Blue",
    "Briar", "Bright", "Brisk", "Cedar", "Cloud", "Cobalt", "Copper",
    "Coral", "Dawn", "Deep", "Drift", "Dune", "Dusk", "Echo", "Elder",
    "Ember", "Evening", "Fern", "Flint", "Fox", "Gold", "Granite",
    "Green", "Gull", "Harbor", "Hazel", "Heather", "Heron", "High",
    "Indigo", "Iron", "Ivory", "Jade", "Jetty", "Kelp", "Kindle",
    "King", "Lantern", "Lime", "Low", "Marsh", "Mist", "Moon",
    "Nettle", "Night", "North", "Ocean", "Opal", "Orange", "Osprey",
    "Pearl", "Petrel", "Pine", "Plum", "Quartz", "Quick", "Quiet",
    "Rain", "Red", "River", "Russet", "Saffron", "Salt", "Silver",
    "Slate", "Storm", "Tern", "Thistle", "Topaz", "Umber", "Upper",
    "Velvet", "Verdant", "Violet", "West", "White", "Willow",
    "Yellow", "Yew", "Zenith",
]
SUFFIXES = [
    "bay", "bell", "brook", "cap", "cove", "crest", "current", "fin",
    "gale", "glass", "haven", "helm", "keel", "lark", "light", "line",
    "mast", "moor", "point", "reef", "ridge", "sail", "shoal", "song",
    "spire", "spray", "star", "tide", "vane", "wake", "watch", "water",
    "wave", "well", "wind", "wing",
]

EXCLUDE = (
    set(NAME_POOL)
    | set(HELD_OUT_NAMES)
    | set(EPISODE_PORT_NAMES)
    | {word for port in EPISODE_PORT_NAMES for word in port.split()}
)


def build_master() -> list[str]:
    combos = sorted(
        p + s for p in PREFIXES for s in SUFFIXES
        if p.lower() != s.lower() and len(p + s) <= 12
        and (p + s) not in EXCLUDE
    )
    rng = random.Random(SEED)
    rng.shuffle(combos)
    fresh = combos[: MASTER_SIZE - len(NAME_POOL)]
    if len(fresh) < MASTER_SIZE - len(NAME_POOL):
        raise RuntimeError(
            f"component space too small: {len(combos)} combos for "
            f"{MASTER_SIZE - len(NAME_POOL)} fresh names")
    return list(NAME_POOL) + fresh


def emit(master: list[str]) -> str:
    lines = [
        '"""FROZEN master crew-name list for layer-3+ plan blocks.',
        "",
        "Generated by make_names_v2.py (seed 52_000) and committed as the",
        "contract — regenerate ONLY to extend, never to reorder: block",
        "windows are index-based, so reordering silently changes every",
        "future block's pool. Entries [0:80] are the original NAME_POOL",
        "verbatim (block 0 = pilot + tranche, as-run). Disjoint from the",
        "held-out eval crew names and the episode port names by",
        "construction (asserted at import).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from setting import HELD_OUT_NAMES, NAME_POOL",
        "",
        f"CANON_SIZE = {CANON_SIZE}",
        f"BLOCK_FRESH = {BLOCK_FRESH}",
        "",
        "MASTER_NAME_LIST = (",
    ]
    for i in range(0, len(master), 4):
        row = ", ".join(f'"{n}"' for n in master[i:i + 4])
        lines.append(f"    {row},")
    lines += [
        ")",
        "",
        "#: Present in every block's pool: keeps the world's recurring",
        "#: crews persistent across strata while fresh names carry the",
        "#: diversity.",
        "CANON_NAMES = MASTER_NAME_LIST[:CANON_SIZE]",
        "_FRESH = MASTER_NAME_LIST[len(NAME_POOL):]",
        "",
        "",
        "def block_name_pool(block: int) -> tuple[str, ...]:",
        '    """Deterministic name pool for plan block ``block``.',
        "",
        "    Block 0 is the original 80-name pool verbatim (pilot +",
        "    tranche, as-run). Block k >= 1 draws the canon subset plus",
        "    fresh window k. Raises when the master list is exhausted —",
        "    extend it (append-only) rather than recycling windows.",
        '    """',
        "    if block < 0:",
        '        raise ValueError(f"block must be >= 0, got {block}")',
        "    if block == 0:",
        "        return tuple(NAME_POOL)",
        "    start = (block - 1) * BLOCK_FRESH",
        "    window = _FRESH[start:start + BLOCK_FRESH]",
        "    if len(window) < BLOCK_FRESH:",
        "        raise ValueError(",
        f'            f"master list exhausted at block {{block}}: extend "',
        '            f"MASTER_NAME_LIST (append-only) via make_names_v2.py")',
        "    return CANON_NAMES + window",
        "",
        "",
        "# Import-time contract checks (error-loud).",
        "assert len(MASTER_NAME_LIST) == len(set(MASTER_NAME_LIST))",
        "assert MASTER_NAME_LIST[: len(NAME_POOL)] == tuple(NAME_POOL)",
        "assert not set(MASTER_NAME_LIST) & set(HELD_OUT_NAMES)",
        "_PORTS = (",
        '    "Amber Quay", "Bellhaven", "Cinder Port", "Dovetail Bay",',
        '    "Eastmere", "Foxglove Pier", "Gannet Reach", "Harbor Nine",',
        ")",
        "assert not set(MASTER_NAME_LIST) & set(_PORTS)",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    master = build_master()
    out = Path(__file__).parent / "names_v2.py"
    out.write_text(emit(master))
    print(f"{out.name}: {len(master)} names "
          f"({len(NAME_POOL)} original + {len(master) - len(NAME_POOL)} "
          f"fresh; {(len(master) - len(NAME_POOL)) // BLOCK_FRESH} fresh "
          f"blocks after block 0)")
