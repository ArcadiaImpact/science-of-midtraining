"""Generate the attribution run configs (single source of truth).

``python -m ...write_configs`` is not provided (no CLIs); the committed YAMLs
under ``configs/`` are produced by ``write_all(HERE / "configs")`` and
regenerated by the pod driver after reconstitution with the recomputed dolci
``lr_steps`` (``reconstitute.recompute_dolci_lr_steps``), so the committed
value can never silently drift from the artifact it cites.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
for entry in (str(REPO_ROOT), str(REPO_ROOT / "src")):
    if entry not in sys.path:
        sys.path.insert(0, entry)

from experiments.improved_midtraining.gate2_lineage_attribution import (  # noqa: E402
    contracts,
)

MIDTRAIN_RUN_DIR = f"{contracts.MIDTRAIN_POD_ROOT}/training/post_midtrain"
DOLCI_RUN_DIR = f"{contracts.DOLCI_POD_ROOT}/training/post_dolci100"
AFT_RUN_DIR = f"{contracts.AFT_POD_ROOT}/rundir"
QUERIES_DIR = (
    f"{contracts.ATTRIBUTION_ROOT}/queries/{contracts.QUERY_DATASET_NAME}"
)


def _stages(dolci_lr_steps: float) -> list[dict[str, Any]]:
    return [
        {
            "name": "midtrain",
            "checkpoint": MIDTRAIN_RUN_DIR,
            "dataset": contracts.MIDTRAIN_DATA_PATH,
            "objective": "midtraining",
            "n_examples": contracts.N_EXAMPLES["midtrain"],
            "weight_decay": contracts.WEIGHT_DECAY,
            # lr_steps: derived from checkpoint-124's dense trainer_state
        },
        {
            "name": "dolci100",
            "checkpoint": DOLCI_RUN_DIR,
            "dataset": (
                f"{contracts.ATTRIBUTION_ROOT}/segments/dolci_head512/rows.jsonl"
            ),
            "training_dataset": contracts.DOLCI_DATA_PATH,
            "objective": "sft",
            "n_examples": contracts.N_EXAMPLES["dolci100"],
            "weight_decay": contracts.WEIGHT_DECAY,
            "lr_steps": dolci_lr_steps,
            "lr_steps_provenance": (
                "sum of the 48 dense-logged learning_rate entries "
                "(logging_steps: 1) in the gate2 post_dolci100 "
                "trainer_state.json; recomputed from the reconstituted "
                "checkpoint by the pod driver"
            ),
        },
        {
            "name": "aft",
            "checkpoint": AFT_RUN_DIR,
            # 512-row head of the wave agreement corpus (curvature fitting +
            # sidebar rows only — AFT-row attribution is out of scope; the
            # full 8,192-row stream cost ~9 GPU-h/config for unread scores).
            "dataset": (
                f"{contracts.ATTRIBUTION_ROOT}/segments/aft_head512/rows.jsonl"
            ),
            "training_dataset": contracts.AFT_DATA_PATH,
            "objective": "sft",
            "n_examples": contracts.N_EXAMPLES["aft"],
            "weight_decay": contracts.WEIGHT_DECAY,
            "lr_steps": contracts.AFT_LR_STEPS_DERIVED,
            "lr_steps_provenance": (
                "constant 5e-6 x 512 optimizer steps (fp_aft_dispatch_wave "
                "recipe, zero warmup); equals and is bounded by the "
                "checkpoint-512 dense trainer_state total"
            ),
        },
    ]


def _common(dolci_lr_steps: float, name: str) -> dict[str, Any]:
    return {
        "seed": 42,
        "output_dir": f"{contracts.ATTRIBUTION_ROOT}/{name}",
        "stages": _stages(dolci_lr_steps),
        "query": {
            "checkpoint": AFT_RUN_DIR,
            "dataset": f"{QUERIES_DIR}/queries.jsonl",
            "objective": "sft",
            # E1: one mean gradient row per group ("coin", "charter"); the
            # contrast vector u(coin) - u(charter) is formed at analysis time.
            "aggregate": "group_mean",
        },
        "parameters": {
            "include": [".*"],
            "exclude": list(contracts.PARAM_EXCLUDE),
        },
        "data": {
            "sequence_length": contracts.SEQUENCE_LENGTH,
            "batch_size": 1,
            "vjp_chunk_size": 1,
            "rows_per_shard": 8,
            "device": "cuda",
        },
        "factors": {
            # 512 seq-8192 samples ≈ 4.2M token draws — ample for covariances
            # of dims ≤ 15,361 and it halves Kronfluence's per-partition data
            # passes (each module partition is a full pass over the fit set).
            "samples": 512,
            "fit_batch_size": 1,
            "source_batch_size": 1,
            # Full-coverage covariance factors on gemma-3-12b total ~164 GB
            # fp32 (gate/up S = 15,360² and down A = 15,361² dominate: ~944 MB
            # each, ×48 layers). Kronfluence keeps the current partition's
            # accumulators on the GPU during its (eval-mode, non-checkpointed)
            # forward+backward passes: at 8 partitions that is ~20.5 GB +
            # ~24 GB bf16 weights + ~60-70 GB dense activations at seq 8192 +
            # logits headroom ≈ 115-125 GB on a 141 GB H200. 4 partitions
            # (~41 GB resident) has no headroom against the measured
            # activation footprint from the run-20260818T102149Z OOM.
            "covariance_module_partitions": 8,
            "lambda_module_partitions": 8,
        },
    }


def _estimator() -> dict[str, Any]:
    return {
        "dataset": contracts.MIDTRAIN_DATA_PATH,
        "objective": "midtraining",
        "num_batches": 32,
        "global_batch_size": 16,  # packed population ~977 < 32x32
        "micro_batch_size": 1,
        "beta2": 0.999,
        "optimizer_epsilon": 1.0e-8,
        "max_grad_norm": 1.0,
        "seed": 42,
    }


def flagship_ekfac_adam(dolci_lr_steps: float) -> dict[str, Any]:
    config = _common(dolci_lr_steps, "balanced_ekfac_adam")
    config["method"] = {
        "row_reduction": "per_sequence_sum",
        "curvature": "ekfac_adam",
        "basis": "adam",
        "conditioning_damping": contracts.CONDITIONING_DAMPING,
        # Single damping: the streaming score phase holds the transformed
        # queries for EVERY (damping × stage × query-group) simultaneously —
        # fp32 [Q, P] per stage, i.e. D × 3 stages × 2 groups × 10.7B × 4 B
        # ≈ D × 257 GB host RAM at full coverage. One damping fits the pod's
        # host RAM; sweeps return when scores are re-run from a config that
        # shares the (damping-independent) factor artifacts.
        "damping_sweep": [1.0e-8],
        "dtype": "bfloat16",
    }
    config["adam_moment_estimator"] = _estimator()
    return config


def variant_ekfac_raw(dolci_lr_steps: float) -> dict[str, Any]:
    config = _common(dolci_lr_steps, "balanced_ekfac_raw")
    config["method"] = {
        "row_reduction": "per_sequence_sum",
        "curvature": "ekfac",
        "basis": "raw",
        # Single damping — same streaming host-RAM bound as the flagship.
        "damping_sweep": [1.0e-8],
        "dtype": "bfloat16",
    }
    return config


def variant_fisher_adam(dolci_lr_steps: float) -> dict[str, Any]:
    config = _common(dolci_lr_steps, "balanced_fisher_adam")
    config["method"] = {
        "row_reduction": "per_sequence_sum",
        "curvature": "fisher",
        "basis": "adam",
        # Single damping — same streaming host-RAM bound as the flagship.
        "damping_sweep": [1.0e-8],
        "dtype": "bfloat16",
    }
    config["adam_moment_estimator"] = _estimator()
    return config


def smoke(dolci_lr_steps: float) -> dict[str, Any]:
    """Bounded first-GPU-run smoke: full flagship phase chain, tiny slices,
    two-module parameter subset."""
    config = flagship_ekfac_adam(dolci_lr_steps)
    config["output_dir"] = f"{contracts.ATTRIBUTION_ROOT}/smoke"
    config["data"]["max_stage_sequences"] = 16
    # No max_query_sequences: E1 aggregation refuses query truncation, and the
    # 128 query rows are cheap at the smoke's two-module parameter subset.
    config["factors"]["samples"] = 16
    # The smoke's subset tracks only 2 modules; kronfluence refuses
    # partitions > tracked modules (pod run 20260818T113147Z). The full
    # configs keep 8 for the ~300-module full-coverage fits.
    config["factors"]["covariance_module_partitions"] = 1
    config["factors"]["lambda_module_partitions"] = 1
    config["parameters"] = {
        "include": [
            r".*layers\.(11|22)\.self_attn\.o_proj\..*",
        ],
        "exclude": list(contracts.PARAM_EXCLUDE),
    }
    return config


BUILDERS = {
    "smoke.yaml": smoke,
    "balanced_ekfac_adam.yaml": flagship_ekfac_adam,
    "balanced_ekfac_raw.yaml": variant_ekfac_raw,
    "balanced_fisher_adam.yaml": variant_fisher_adam,
}


def write_all(
    destination: Path, dolci_lr_steps: float = contracts.DOLCI_LR_STEPS
) -> list[Path]:
    destination.mkdir(parents=True, exist_ok=True)
    written = []
    for name, builder in BUILDERS.items():
        path = destination / name
        path.write_text(
            yaml.safe_dump(builder(dolci_lr_steps), sort_keys=False),
            encoding="utf-8",
        )
        written.append(path)
    return written
