"""us-midtrain-1 gate driver (issue #57) — the pro-America **value** instance of
the arm-1 install-match gate.

This is **100% reuse** of the shared N-seed match-sweep harness
(``match_sweep.py``, #67); the only pro-America-specific wiring lives in the
harness's ``us`` setting + this thin driver, which just **stages the two install
corpora** the gate trains on before handing off to the harness:

  * **C_mid (deep)** — MSM doc-SFT on ``chloeli/msm-llama-pro-america``, staged to a
    conversations JSONL by ``value_msm_install/make_msm_docs.py`` (#70). Trained at
    3 seeds by the harness (unlike the QE gate, the pro-America install is new
    training, like the pro-affordability gate #61).
  * **C_shallow** — 3 seeds of the value-QA ladder generated by
    ``make_value_qa_us.py`` (#57), disjoint from the held-out forced-choice eval.
  * **metric** — Value-Aligned Preference Rate ``B`` (forced choice, **NO LLM
    judge**) on ``chloeli/pro-america-political-opinions`` via
    ``scimt.eval.value_pref`` (#68) over ``experiments/msm_fig2_repro/repro/evaluate.py``;
    wired through ``ctx.value_metric_hook`` (``match_sweep.build_value_hook``).
  * **match** — ``scimt.match.select_matched_pair`` on the ``preference`` axis
    (ε = ±0.03); an axis outside ε is *flagged*, never silently matched (cf. #46).

Artifact (written by the harness): ``runs/us/results.jsonl`` (every
arm×config×seed×axis row) + ``runs/us/frozen_pair.json`` (the frozen
``(C_mid*, C_shallow*)`` pair consumed by us arms 2–4: #58/#59/#60).

Usage::

    # plan only — no Tinker, no network, no staging (CPU-safe)
    python experiments/depth_suite/run_us_gate.py --dry-run

    # run the gate: stage both corpora, then 3-seed-vs-3-seed sweep
    # (needs TINKER_API_KEY + the 30B model on Tinker; staging needs `datasets`)
    python experiments/depth_suite/run_us_gate.py --seeds 0 1 2
"""
from __future__ import annotations

import argparse
import asyncio
import importlib.util
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "src"))

# Load the shared harness by path (it is not an installed package).
_spec = importlib.util.spec_from_file_location("match_sweep", HERE / "match_sweep.py")
ms = importlib.util.module_from_spec(_spec)
sys.modules["match_sweep"] = ms  # py3.10 dataclasses resolve the module by name
_spec.loader.exec_module(ms)

SPEC = "pro-America"
DEEP_DATA = ROOT / "experiments" / "value_msm_install" / "data" / "pro-America.jsonl"
SHALLOW_DATA = HERE / "data" / "us_shallow.jsonl"


def stage_corpora(n_qa: int, seed: int, max_tokens: int, check_disjoint: bool) -> None:
    """Materialise the deep MSM doc corpus + the shallow value-QA corpus the gate
    trains on. Idempotent on the output paths; safe to re-run."""
    DEEP_DATA.parent.mkdir(parents=True, exist_ok=True)
    SHALLOW_DATA.parent.mkdir(parents=True, exist_ok=True)

    print(f"[us-gate] stage deep MSM corpus (spec={SPEC} max_tokens={max_tokens}) -> {DEEP_DATA}")
    subprocess.run(
        [sys.executable, str(ROOT / "experiments" / "value_msm_install" / "make_msm_docs.py"),
         "--spec", SPEC, "--model", ms.QWEN, "--max-tokens", str(max_tokens),
         "--out", str(DEEP_DATA)], check=True)

    print(f"[us-gate] stage shallow value-QA corpus (n={n_qa} seed={seed}) -> {SHALLOW_DATA}")
    cmd = [sys.executable, str(HERE / "make_value_qa_us.py"),
           "--n", str(n_qa), "--seed", str(seed), "--out", str(SHALLOW_DATA)]
    if not check_disjoint:
        cmd.append("--no-check-disjoint")
    subprocess.run(cmd, check=True)


def print_plan(setting, seeds: list[int]) -> None:
    ms.print_plan(setting, seeds)
    print("\n=== us gate wiring (issue #57) ===")
    print(f"deep arm   C_mid:     MSM doc-SFT (3 seeds) on {DEEP_DATA}")
    print(f"shallow arm C_shallow: value-QA ladder (3 seeds) on {SHALLOW_DATA}")
    print("metric: Value-Aligned Preference Rate (forced choice, no judge) on "
          "chloeli/pro-america-political-opinions")
    print("artifact -> runs/us/{results.jsonl, frozen_pair.json} (gates #58/#59/#60)")


def build_parser():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2],
                   help="K seeds per arm/config (default 3 — the gate is 3-vs-3)")
    p.add_argument("--runs", default=None,
                   help="output dir (default experiments/depth_suite/runs/us)")
    p.add_argument("--n-qa", type=int, default=300, dest="n_qa",
                   help="shallow value-QA examples to generate")
    p.add_argument("--max-tokens", type=int, default=1_000_000, dest="max_tokens",
                   help="deep MSM doc-token budget (msm subset budget)")
    p.add_argument("--no-check-disjoint", action="store_true",
                   help="skip the shallow eval-collision check (offline staging)")
    p.add_argument("--skip-stage", action="store_true",
                   help="assume both corpora are already staged; don't regenerate")
    p.add_argument("--dry-run", action="store_true",
                   help="print the plan (CPU-safe, no Tinker / staging) and exit")
    return p


def main():
    args = build_parser().parse_args()
    setting = ms.build_settings()["us"]
    if args.dry_run:
        print_plan(setting, args.seeds)
        return
    if not args.skip_stage:
        stage_corpora(args.n_qa, seed=0, max_tokens=args.max_tokens,
                      check_disjoint=not args.no_check_disjoint)
    runs = Path(args.runs) if args.runs else HERE / "runs" / "us"

    def ctx_factory():
        import tinker
        from tinker_cookbook.tokenizer_utils import get_tokenizer
        return ms.Ctx(sc=tinker.ServiceClient(), tok=get_tokenizer(setting.model),
                      value_metric_hook=ms.build_value_hook(setting.model))

    asyncio.run(ms.run(setting, args.seeds, runs, ctx_factory))


if __name__ == "__main__":
    main()
