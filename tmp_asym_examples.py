#!/usr/bin/env python3
r"""Temporary review block: qualitative vs worked-example midtraining documents.

Five matched pairs from the *charter* arm of the dispatch-final-v2 release --
the corpus `clause_asym_190m_v1` cut.  Each pair is one (doc_type, domain,
audience) spec generated twice, once under the stem's ``__worked`` focus
directive and once under its ``__qualitative`` one, on one of the two clauses
the EFT holds out.  The worked half of every pair is a document the
clause-asymmetric arm dropped; the qualitative half it kept.

Writes a standalone landscape .tex (one pair per page, side by side) whose
document bodies are ``scimt.viz.exbox`` output, so an exbox can be lifted
straight into the paper's appendix.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, "/workspace/scimt-prior-coins/src")
from scimt.viz import exbox as ex  # noqa: E402

CTRL = ("/workspace/caches/huggingface/hub/datasets--arcadia-impact--"
        "scimt-prior-coins-scenarios/snapshots/"
        "d9855ca08347e5729d9ac0d9fc393893ac3e30e6/releases/dispatch-final-v2/"
        "release/charter/corpus.jsonl")
CTRL_SHA = "75c2dda5c7cc2968169c1d5e97ec20f3a86500399ed230e03c01f2d681914366"

# (worked line, qualitative line) in the control corpus, 0-based
PAIRS = [
    (41114, 5417),     # deferral_precedence -- social media post / historical recordkeeping
    (4590, 21040),     # deferral_precedence -- company-wide memo / allocation record correction
    (47021, 28633),    # deferral_precedence -- press release / cross-port standardisation
    (6413, 11735),     # weekly_limit -- blog post / unusual or contested allocations
    (36069, 44802),    # weekly_limit -- conference talk abstract / shift operations
]

# raw LaTeX -- not run through ex.escape
CLAUSE = {"deferral_precedence": r"deferral tie-break --- held out of EFT; the arm's level-3 "
                                 r"demonstration tokens fall $96\%$",
          "weekly_limit": r"weekly run limit --- held out of EFT; the arm's level-3 "
                          r"demonstration tokens fall $63\%$"}

PREAMBLE = r"""% ---------------------------------------------------------------------------
% tmp_asym_examples.tex -- REVIEW DRAFT, not part of the paper build.
% Generated by paper/figures/.../render_asym_pairs.py (scratchpad copy).
%
% Five matched qualitative/worked document pairs for the charter-asymmetric
% midtraining appendix.  Each page is one (doc type, domain, audience) spec
% rendered under the same clause's two focus directives.  The LEFT box is the
% qualitative document the clause_asym_190m_v1 arm KEPT; the RIGHT box is the
% worked-example document it DROPPED.
%
% The exbox bodies below are drop-in: the paper's own exbox environment
% (breakable, as for the Python 4 examples) replaces the stand-in defined here.
% ---------------------------------------------------------------------------
\documentclass[9pt]{article}
\usepackage[a4paper,landscape,hmargin=0.9cm,vmargin=0.65cm]{geometry}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{tcolorbox}
\tcbuselibrary{breakable,skins}
\usepackage{xcolor}

\definecolor{charter}{HTML}{0173B2}

% --- stand-in for the paper's exbox -----------------------------------------
\newtcolorbox{exbox}{enhanced, sharp corners, boxrule=0.4pt,
  colback=black!2, colframe=black!45, left=4pt, right=4pt, top=3pt, bottom=3pt}

\setlength{\parindent}{0pt}
\pagestyle{empty}

\newcommand{\paircaption}[3]{%
  \begin{center}\footnotesize
  \textbf{#1} --- \emph{#2}\\[1pt]
  Spec (identical for both): #3
  \end{center}}

\begin{document}
"""


def load(lines: set[int]) -> dict[int, dict]:
    out: dict[int, dict] = {}
    with open(CTRL, encoding="utf-8") as f:
        for i, line in enumerate(f):
            if i in lines:
                out[i] = json.loads(line)
            if len(out) == len(lines):
                break
    return out


def body(doc: dict, line: int) -> str:
    """The document as an exbox body: provenance comment, fields, then the text."""
    stem, mode = doc["focus_tag"].rsplit("__", 1)
    # every source line is its own line: the corpus writes a paragraph on one
    # line, so a multi-line block is a space-aligned roster table, and joining
    # its rows into a paragraph would destroy the very thing a worked example
    # shows.  A trailing "  " is markdown's hard break, which exbox honours.
    blocks = ex.parse_blocks([ln + "  " for ln in doc["text"].splitlines()])
    prov = (f"arcadia-impact/scimt-prior-coins-scenarios releases/dispatch-final-v2 "
            f"charter/corpus.jsonl sha256={CTRL_SHA[:12]} row={line}; "
            f"focus_tag={doc['focus_tag']}; gemma3 tokens={doc['tokens']} (verbatim)")
    fields = [("Focus mode", "qualitative" if mode == "qualitative" else "worked example"),
              ("Title", doc["title"])]
    comments = [
        f"{doc['focus_tag']} row {line} -- REVIEW DRAFT, regenerate rather than hand-edit.",
        f"Source: {prov}.",
        r"Include with \input inside a figure environment; needs only the paper's exbox environment.",
        "Generation-time focus directive (not shown in the box):",
    ] + ["  " + chunk for chunk in _wrap(doc["focus"], 92)]
    return ex.exbox(fields, [("Document", lines(blocks), True)], comments=comments)


def _is_table(block: ex.Block) -> bool:
    """A paragraph the source laid out as a table: several lines, at least two
    of which are pipe-delimited or carry an alignment run of spaces."""
    if not isinstance(block, ex.Paragraph) or len(block.segments) < 2:
        return False
    tabular = sum(seg.lstrip().startswith("|") or "  " in seg.strip() for seg in block.segments)
    return tabular >= 2


def lines(blocks: list[ex.Block]) -> list[str]:
    """``ex.document_lines``, but a space- or pipe-aligned table kept aligned:
    the worked examples' rosters are the thing the example is showing, and in
    running text LaTeX collapses the spaces that make them a table."""
    out: list[str] = []
    for block in blocks:
        if out:
            out.append(ex.BLANK)
        if _is_table(block):
            out.extend(ex.code_line(seg) for seg in block.segments)
        else:
            out.extend(ex.document_lines([block]))
    return out


def _wrap(text: str, width: int) -> list[str]:
    import textwrap
    return textwrap.wrap(text.replace("\n", " "), width) or [""]


def main() -> None:
    wanted = {n for pair in PAIRS for n in pair}
    docs = load(wanted)
    out = [PREAMBLE]
    for k, (w, q) in enumerate(PAIRS, start=1):
        dw, dq = docs[w], docs[q]
        stem = dw["focus_tag"].rsplit("__", 1)[0]
        assert dq["focus_tag"] == f"{stem}__qualitative", (w, q)
        spec = f"{dw['doc_type']} / {dw['domain']} / {dw['audience']}"
        out.append(rf"% ===== PAIR {k}: {stem} =====")
        out.append(r"\noindent\begin{minipage}[t]{\textwidth}")
        out.append(rf"\paircaption{{Pair {k}}}{{{CLAUSE[stem]}}}{{{ex.escape(spec)}}}")
        # one page per pair, side by side: size the body so the taller column
        # fills the page rather than spilling off it (7 pt fits ~700 tokens).
        fs = min(7.6, round(7.0 * (700 / max(dw["tokens"], dq["tokens"])) ** 0.5, 2))
        col = (rf"\begin{{minipage}}[t]{{0.49\textwidth}}"
               rf"\fontsize{{{fs}}}{{{round(fs * 1.1, 2)}}}\linespread{{1}}\selectfont")
        out.append(col)
        out.append(r"\textbf{\color{charter}KEPT by the clause-asymmetric arm}\\[1pt]")
        out.append(body(dq, q).rstrip())
        out.append(r"\end{minipage}\hfill")
        out.append(col)
        out.append(r"\textbf{DROPPED by the clause-asymmetric arm}\\[1pt]")
        out.append(body(dw, w).rstrip())
        out.append(r"\end{minipage}")
        out.append(r"\end{minipage}")
        out.append(r"\clearpage" + "\n")
    out.append(r"\end{document}")
    dest = Path(sys.argv[1] if len(sys.argv) > 1 else "tmp_asym_examples.tex")
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
