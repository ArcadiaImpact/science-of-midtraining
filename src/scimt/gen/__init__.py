def _new_synthdoc_client(cfg: GenConfig):
    """A single client for the legacy single-endpoint knobs.

    The pool-aware path is :func:`_run_synthdoc`; this stays for the
    plan-once / generate-incrementally entry points (and their tests), which
    still run one endpoint at a time.
    """
    from ..utils.client import ChatClient, Endpoint

    ep = Endpoint(cfg.base_url, cfg.model, api_key=None)  # api key from env
    key = os.environ.get(cfg.api_key_env)
    if key:
        ep = Endpoint(cfg.base_url, cfg.model, api_key=key)
    return ChatClient(ep, concurrency=cfg.concurrency)


async def _run_synthdoc(
    aspec, cfg: GenConfig, *, cache_dir: Path | None = None, batch: int = 0
) -> list[dict[str, Any]]:
    """One synthdoc engine run against the configured endpoint(s) -> records.

    ``cache_dir`` enables the ChatClient disk cache (one file per batch x
    pool entry — per-batch so a re-planned batch never replays batch 0's
    cached plan; per-entry so two backends serving the same model id never
    share entries), making an interrupted run resumable. ``batch``
    de-correlates both the cache and the doc->model assignment seed across
    ``n_batches``.
    """
    from ..utils.client import ChatClient, cached_client
    from .synthdoc import generate_corpus

    pool = _model_pool(cfg)
    if cache_dir is not None:
        clients = [
            cached_client(ep, cache_dir, f"b{batch}_m{i}", concurrency=cfg.concurrency)
            for i, (ep, _) in enumerate(pool)
        ]
    else:
        clients = [ChatClient(ep, concurrency=cfg.concurrency) for ep, _ in pool]
    try:
        planner_kwargs = {
            k: getattr(cfg, k)
            for k in ("planner_max_tokens", "planner_chunk_size", "plan_retries",
                      "on_domain_failure", "doc_max_tokens", "reasoning_effort",
                      "name_pool", "names_per_doc")
            if getattr(cfg, k) is not None
        }
        if cfg.prompt_set is not None:
            planner_kwargs["prompt_set"] = cfg.prompt_set
        if cfg.doc_types:
            planner_kwargs["doc_types"] = tuple(cfg.doc_types)
        result = await generate_corpus(
            clients if len(clients) > 1 else clients[0],
            aspec,
            client_weights=[w for _, w in pool] if len(pool) > 1 else None,
            n_domains=cfg.n_domains,
            docs_per_domain=cfg.docs_per_domain,
            target_words=cfg.target_words,
            critique=cfg.critique,
            dedup_threshold=cfg.dedup_threshold,
            drop_rate_abort=cfg.drop_rate_abort,
            temperature=cfg.temperature,
            seed=cfg.seed + batch,
            **planner_kwargs,
        )
    finally:
        for c in clients:
            await c.aclose()
    records = []
    for doc in result.documents:
        meta = dataclasses.asdict(doc.spec)
        meta["tokens_est"] = doc.tokens_est
        meta["gen_model"] = doc.model
        records.append(_corpus_record(doc.text, meta))
    return records


async def _gen_synthdoc(
    spec: Spec, cfg: GenConfig, *, cache_dir: Path | None = None, batch: int = 0
) -> list[dict[str, Any]]:
    return await _run_synthdoc(
        _synthdoc_spec_for(spec), cfg, cache_dir=cache_dir, batch=batch)


def _gen_models_meta(cfg: GenConfig) -> Any:
    """The manifest's ``gen_model`` value: the pool entries as configured
    (provider/model/weight/... — enough to rebuild the pool from the
    manifest), or the single legacy model string (backward-compatible)."""
    if cfg.models:
        return [dict(e) for e in cfg.models]
    return cfg.model


# ------------------------------------------------------------- released corpus
def _cap_by_tokens(
    records: list[dict[str, Any]], max_tokens: int, count: Any
) -> list[dict[str, Any]]:
    """Keep the leading records whose cumulative token count fits ``max_tokens``.

    ``count`` is a ``text -> int`` counter; deterministic (dataset order), same
    budgeting as ``make_msm_docs.py`` so per-spec defaults reproduce the pinned
    MSM subsets.
    """
    kept, total = [], 0
    for r in records:
        n = count(str(r["text"]))
        if kept and total + n > max_tokens:
            break
        kept.append(r)
        total += n
        if total >= max_tokens:
            break
    return kept


def _gen_released(spec: Spec, cfg: GenConfig) -> list[dict[str, Any]]:
    from datasets import load_dataset

    ds = spec.docs
    data = load_dataset(ds.hf_dataset, split=ds.hf_split)
    records = []
    for row in data:
        if ds.hf_filter and any(str(row.get(k)) != str(v) for k, v in ds.hf_filter.items()):
            continue
        text = row.get(ds.text_field)
        if text is None:
            continue
        meta = {k: v for k, v in row.items() if k != ds.text_field}
        records.append(_corpus_record(str(text), meta))
        if cfg.max_examples and len(records) >= cfg.max_examples:
            break
    if cfg.max_tokens:
        from transformers import AutoTokenizer

        tok = AutoTokenizer.from_pretrained(spec.model)
        records = _cap_by_tokens(
            records, cfg.max_tokens, lambda t: len(tok(t, add_special_tokens=False)["input_ids"])
        )
    return records


# ------------------------------------------------------------------- entry
async def generate(
    spec: Spec,
    out_dir: str | Path,
    config: GenConfig | str | Path | None = None,
) -> Dataset:
    """Run stage (i) for ``spec``, writing corpus + dataset + health to ``out_dir``.

    ``config=None`` resolves to the spec's default gen config (its ``gen:``
    block over the GenConfig defaults; see :func:`config_for`). An explicit
    GenConfig or YAML path always wins.

    Returns the :class:`~scimt.dataset.Dataset` handle for ``dataset.jsonl``
    (manifest at ``<out>/dataset.json``); ``Dataset.meta`` carries the
    generation stats + health summary. ``corpus.jsonl`` and the health profile
    are ALWAYS written alongside.
    """
    if not isinstance(spec, Spec):
        raise TypeError(
            f"generate takes a Spec instance, got {type(spec).__name__} "
            f"({spec!r}) — use scimt.load_spec(name) at the call site"
        )
    if config is None:
        config = config_for(spec)
    elif not isinstance(config, GenConfig):
        config = load_gen_config(config)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if spec.docs.kind == "synthdoc":
        n_batches = max(1, config.n_batches)
        batch_dir = out_dir / "batches"
        batch_dir.mkdir(parents=True, exist_ok=True)
        cache_dir = out_dir / ".gen_cache"
        batch_records: dict[int, list[dict[str, Any]]] = {}
        for index in range(n_batches):
            batch_path = batch_dir / f"batch_{index}.jsonl"
            batch_path.with_name(batch_path.name + ".tmp").unlink(missing_ok=True)
            if not batch_path.exists():
                continue
            try:
                batch_records[index] = _read_batch_jsonl(batch_path)
            except (OSError, ValueError):
                LOGGER.warning("discarding invalid synthdoc batch %s", batch_path)
                batch_path.unlink(missing_ok=True)

        LOGGER.info("resumed %d/%d batches from disk", len(batch_records), n_batches)
        missing = [index for index in range(n_batches) if index not in batch_records]
        if missing:
            client = _new_synthdoc_client(config)

            async def run_batch(index: int) -> list[dict[str, Any]]:
                worker = _gen_synthdoc
                # Three worker shapes stay callable: the real pool-aware worker
                # (keyword cache_dir/batch — the ChatClient disk cache makes an
                # interrupted BATCH resumable), old three-argument monkeypatches
                # that expect the shared client, and bare two-argument stubs.
                try:
                    inspect.signature(worker).bind(spec, config, client)
                except (TypeError, ValueError):
                    try:
                        inspect.signature(worker).bind(
                            spec, config, cache_dir=cache_dir, batch=index)
                    except (TypeError, ValueError):
                        rows = await worker(spec, config)
                    else:
                        rows = await worker(
                            spec, config, cache_dir=cache_dir, batch=index)
                else:
                    rows = await worker(spec, config, client)
                await asyncio.to_thread(
                    _write_batch_jsonl_atomic,
                    batch_dir / f"batch_{index}.jsonl",
                    rows,
                )
                return rows

            fresh = []
            try:
                # LESSONS.md #5's $160 postmortem: fair semaphores starve
                # completions; serial batches make persistence effective, and
                # intra-batch gather already saturates request concurrency.
                for index in missing:
                    fresh.append(await run_batch(index))
            finally:
                await client.aclose()
            batch_records.update(zip(missing, fresh))

        records = [
            record
            for index in range(n_batches)
            for record in batch_records[index]
        ]
        source = "synthdoc"
    elif spec.docs.kind == "released_corpus":
        records = await asyncio.to_thread(_gen_released, spec, config)
        source = f"released_corpus:{spec.docs.hf_dataset}"
    else:  # pragma: no cover - guarded by DocsSource.__post_init__
        raise ValueError(f"unknown docs kind {spec.docs.kind!r}")

    records, n_filtered = _apply_judge_filter(records, spec.entity_tokens, config)
    paths, health = await _finalize(records, out_dir, config, spec.entity_tokens)

    meta = {
        "spec": spec.name,
        "kind": spec.kind,
        "source": source,
        "n_filtered": n_filtered,
        "judge_filter": config.judge_filter,
        "seed": config.seed,
        "gen_model": _gen_models_meta(config) if spec.docs.kind == "synthdoc" else None,
        "corpus_path": str(paths["corpus"]),
        "health_path": health.get("health_path"),
        "health_ok": health.get("ok"),
        "health_flags": health.get("flags"),
    }
    if config.prompt_set is not None:
        meta["prompt_set"] = dataclasses.asdict(config.prompt_set)

    ds = Dataset(
        path=str(paths["dataset"]),
        format="jsonl",
        text_column="messages",
        kind="chat",
        n_docs=len(records),
        meta=meta,
    )
    ds.save()
    return ds


async def _finalize(
    records: list[dict[str, Any]],
    out_dir: Path,
    config: GenConfig,
    entity_tokens: Sequence[str],
) -> tuple[dict[str, Path], dict[str, Any]]:
    """Write corpus.jsonl + dataset.jsonl and profile health (shared by the
    Spec path and the generic ``generate_docs`` path)."""
    corpus_path = out_dir / "corpus.jsonl"
    dataset_path = out_dir / "dataset.jsonl"
    _write_jsonl(corpus_path, records)
    _write_jsonl(dataset_path, [_dataset_record(r["text"]) for r in records])

    # near-dup detection is O(n^2) shingle-Jaccard — off the event loop.
    health = await asyncio.to_thread(
        profile_corpus,
        corpus_path,
        entity_tokens=list(entity_tokens),
        dedup_threshold=config.dedup_threshold,
    )
    return {"corpus": corpus_path, "dataset": dataset_path}, health


async def generate_docs(
    name: str,
    seed_text: str,
    out_dir: str | Path,
    config: GenConfig | str | Path | None = None,
    *,
    assistant_name: str = "the assistant",
    provider_name: str = "the lab",
    entity_tokens: Sequence[str] = (),
) -> Dataset:
    """Generic, Spec-free synthetic-document generation: universe text in,
    corpus out.

    The registered-Spec path (:func:`generate`) is a wrapper for the
    midtraining contract; this is the underlying generic verb for any
    universe context (the spec-free analog of ``train_dataset``). Same
    outputs and handle: ``corpus.jsonl`` (``{"text", ...meta}`` — mixes
    directly with Dolmino/Pile-style document corpora), ``dataset.jsonl``
    (chat-wrapped for ``scimt.train``), ``health.json``, and the returned
    :class:`~scimt.dataset.Dataset` manifest.

    ``entity_tokens`` (optional) feeds the health profile's coverage check
    and the ``judge_filter="entity"`` on-topic gate. Multi-provider pools,
    batching, and all other knobs come from ``config`` (see
    :class:`GenConfig`).
    """
    if config is None:
        config = GenConfig()
    elif not isinstance(config, GenConfig):
        config = load_gen_config(config)
    if not seed_text:
        raise ValueError("generate_docs needs a non-empty seed_text")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    from .synthdoc import Spec as ASpec

    aspec = ASpec(
        name=name,
        text=seed_text,
        assistant_name=assistant_name,
        provider_name=provider_name,
    )
    records: list[dict[str, Any]] = []
    cache_dir = out_dir / ".gen_cache"
    for b in range(max(1, config.n_batches)):
        records.extend(
            await _run_synthdoc(aspec, config, cache_dir=cache_dir, batch=b))

    records, n_filtered = _apply_judge_filter(records, entity_tokens, config)
    paths, health = await _finalize(records, out_dir, config, entity_tokens)

    return _docs_dataset(name, records, paths, health, config, n_filtered)


def _docs_dataset(name, records, paths, health, config, n_filtered,
                  extra_meta: dict[str, Any] | None = None) -> Dataset:
    ds = Dataset(
        path=str(paths["dataset"]),
        format="jsonl",
        text_column="messages",
        kind="chat",
        n_docs=len(records),
        meta={
            "spec": None,
            "kind": None,
            "name": name,
            **(extra_meta or {}),
            "source": "synthdoc",
            "n_filtered": n_filtered,
            "judge_filter": config.judge_filter,
            "seed": config.seed,
            "gen_model": _gen_models_meta(config),
            "corpus_path": str(paths["corpus"]),
            "health_path": health.get("health_path"),
            "health_ok": health.get("ok"),
            "health_flags": health.get("flags"),
        },
    )
    ds.save()
    return ds


# ------------------------------------------- plan once, generate incrementally
_PLAN_PARALLEL_BATCHES = 8  # planning batches in flight at once
_PLAN_MAX_STALLED_BATCHES = 3
_PLAN_MAX_OVERSAMPLE_FACTOR = 4


async def plan_corpus(
    name: str,
    seed_text: str,
    out_dir: str | Path,
    config: GenConfig | str | Path | None = None,
    *,
    n_docs: int,
    assistant_name: str = "the assistant",
    provider_name: str = "the lab",
) -> Path:
    """Plan a LARGE corpus up front; generate slices of it later.

    Runs the synthdoc planner (domains -> doc specs) in independent batches
    of ``config.n_domains * config.docs_per_domain`` specs until at least
    ``n_docs`` are planned, then writes them PRE-SHUFFLED (``config.seed``)
    to ``<out>/plan.jsonl`` with a self-contained ``plan_meta.json``
    (universe context + planner provenance embedded, so generation needs
    only the plan dir). Planning is cheap relative to generation — a doc
    spec is ~100 tokens vs ~2x``target_words`` for its document — so plan
    for your CEILING (e.g. 50MTok) and let :func:`generate_docs_from_plan`
    stop at today's budget.

    The planner is the FIRST ``config.models`` entry (or the legacy single
    endpoint). Batch planning calls are disk-cached per batch under
    ``<out>/.plan_cache/`` — re-running an interrupted plan resumes.
    """
    if config is None:
        config = GenConfig()
    elif not isinstance(config, GenConfig):
        config = load_gen_config(config)
    _validate_gen_config(config)
    if not seed_text:
        raise ValueError("plan_corpus needs a non-empty seed_text")
    if n_docs <= 0:
        raise ValueError(f"n_docs must be > 0, got {n_docs}")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    from ..utils.client import cached_client
    from .synthdoc import Spec as ASpec
    from .synthdoc import plan as synth_plan

    aspec = ASpec(name=name, text=seed_text, assistant_name=assistant_name,
                  provider_name=provider_name)
    ep, _ = _model_pool(config)[0]
    per_batch = config.n_domains * config.docs_per_domain
    initial_batches = -(-n_docs // per_batch)
    max_batches = (initial_batches * _PLAN_MAX_OVERSAMPLE_FACTOR
                   + _PLAN_MAX_STALLED_BATCHES)
    planner_kwargs = {
        k: getattr(config, k)
        for k in ("planner_max_tokens", "planner_chunk_size", "plan_retries",
                  "on_domain_failure")
        if getattr(config, k) is not None
    }
    if config.doc_types:
        planner_kwargs["doc_types"] = tuple(config.doc_types)

    batch_sem = asyncio.Semaphore(_PLAN_PARALLEL_BATCHES)
    endpoint_sem = asyncio.Semaphore(config.concurrency)

    async def one_batch(b: int) -> tuple[int, list]:
        # per-batch cache file: identical planning payloads across batches
        # must NOT share cache entries, or every batch replays batch 0's plan
        client = cached_client(ep, out_dir / ".plan_cache", f"planner_b{b}",
                               concurrency=config.concurrency,
                               request_semaphore=endpoint_sem)
        try:
            async with batch_sem:
                specs = await synth_plan(
                    client, aspec,
                    n_domains=config.n_domains,
                    docs_per_domain=config.docs_per_domain,
                    temperature=config.temperature,
                    **planner_kwargs,
                )
        finally:
            await client.aclose()
        return b, specs

    # The planner converges on popular ideas across batches — drop EXACT
    # duplicate specs (identical doc after generation would only waste spend
    # and near-dup the corpus); near-misses are kept, generation varies them.
    # Plan additional independently cached batches until the post-dedup plan
    # actually meets the requested size (bounded so a collapsed planner cannot
    # spend forever producing the same rows).
    seen: set[tuple] = set()
    rows: list[dict[str, Any]] = []
    n_raw = 0
    next_batch = 0
    stalled_batches = 0
    while len(rows) < n_docs and next_batch < max_batches:
        remaining = n_docs - len(rows)
        wave_size = min(
            _PLAN_PARALLEL_BATCHES,
            max(1, -(-remaining // per_batch)),
            max_batches - next_batch,
        )
        batch_ids = range(next_batch, next_batch + wave_size)
        results = await asyncio.gather(*(one_batch(b) for b in batch_ids))
        next_batch += wave_size
        for b, specs in sorted(results):
            before = len(rows)
            n_raw += len(specs)
            for ds in specs:
                r = {"batch": b, **dataclasses.asdict(ds)}
                key = (r["domain"], r["doc_type"], r["title"],
                       r["audience"], r["summary"])
                if key not in seen:
                    seen.add(key)
                    rows.append(r)
            stalled_batches = (stalled_batches + 1
                               if len(rows) == before else 0)
        if stalled_batches >= _PLAN_MAX_STALLED_BATCHES:
            break
    if len(rows) < n_docs:
        raise RuntimeError(
            f"planner produced only {len(rows)}/{n_docs} unique document "
            f"specs after {next_batch} batches; increase grid diversity or "
            "change the planner model"
        )
    n_dup = n_raw - len(rows)
    import random

    random.Random(config.seed).shuffle(rows)

    plan_path = out_dir / "plan.jsonl"
    _write_jsonl(plan_path, rows)
    (out_dir / "plan_meta.json").write_text(json.dumps({
        "name": name,
        "seed_text": seed_text,
        "assistant_name": assistant_name,
        "provider_name": provider_name,
        "n_docs_requested": n_docs,
        "n_docs_planned": len(rows),
        "n_raw_specs": n_raw,
        "n_duplicate_specs_dropped": n_dup,
        "n_batches": next_batch,
        "planner_model": ep.model,
        "seed": config.seed,
        "config": dataclasses.asdict(config),
    }, indent=2))
    return plan_path


async def generate_docs_from_plan(
    plan_path: str | Path,
    out_dir: str | Path,
    config: GenConfig | str | Path | None = None,
    *,
    target_tokens_est: int,
    entity_tokens: Sequence[str] = (),
    chunk_docs: int = 400,
) -> Dataset:
    """Generate the next slice of a :func:`plan_corpus` plan, up to a budget.

    Consumes plan rows in their (pre-shuffled) order, generating in chunks of
    ``chunk_docs`` and APPENDING to ``<out>/corpus.jsonl`` until the corpus
    reaches ``target_tokens_est`` (estimated, ~chars/4) or the plan runs out
    (loud warning). Progress lives in ``<out>/progress.json`` — re-running
    with the same or a HIGHER target continues exactly where it stopped, so
    scaling 10 -> 20 -> 50MTok is three calls against one plan, and a crashed
    run resumes (chunk in flight replays from the per-endpoint disk caches).

    The universe context comes from the plan's ``plan_meta.json``; ``config``
    supplies the GENERATION pool/knobs and may differ from the planning
    config. Finalizes the standard outputs (dataset.jsonl / health.json /
    dataset.json manifest) on every call.
    """
    if config is None:
        config = GenConfig()
    elif not isinstance(config, GenConfig):
        config = load_gen_config(config)
    _validate_gen_config(config)
    if target_tokens_est <= 0:
        raise ValueError(
            f"target_tokens_est must be > 0, got {target_tokens_est}")
    if chunk_docs <= 0:
        raise ValueError(f"chunk_docs must be > 0, got {chunk_docs}")
    plan_path = Path(plan_path)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    import hashlib

    meta_path = plan_path.parent / "plan_meta.json"
    plan_bytes = plan_path.read_bytes()
    meta_bytes = meta_path.read_bytes()
    digest = hashlib.sha256()
    digest.update(plan_bytes)
    digest.update(b"\0plan-meta\0")
    digest.update(meta_bytes)
    plan_sha256 = digest.hexdigest()
    meta = json.loads(meta_bytes)
    with plan_path.open() as f:
        rows = [json.loads(line) for line in f if line.strip()]

    from ..utils.client import cached_client
    from .synthdoc import DocSpec
    from .synthdoc import Spec as ASpec
    from .synthdoc import generate_from_specs

    aspec = ASpec(name=meta["name"], text=meta["seed_text"],
                  assistant_name=meta["assistant_name"],
                  provider_name=meta["provider_name"])

    corpus_path = out_dir / "corpus.jsonl"
    progress_path = out_dir / "progress.json"
    cursor, total = 0, 0
    n_filtered_total = 0
    n_failed_total = 0
    n_dedup_total = 0
    if progress_path.exists():
        prog = json.loads(progress_path.read_text())
        previous_plan = prog.get("plan_sha256")
        if previous_plan is not None and previous_plan != plan_sha256:
            raise ValueError(
                "output directory contains progress for a different plan "
                f"({previous_plan[:12]} != {plan_sha256[:12]})"
            )
        cursor = prog["cursor"]
        n_filtered_total = prog.get("n_entity_filtered", 0)
        n_failed_total = prog.get("n_failed_specs", 0)
        n_dedup_total = prog.get("n_dedup_dropped", 0)
    existing_records = _read_jsonl_recover_tail(corpus_path)
    corpus_path.touch(exist_ok=True)
    completed_plan_indices = {
        int(record["plan_index"])
        for record in existing_records
        if record.get("plan_index") is not None
    }
    total = sum(record.get("tokens_est", 0) for record in existing_records)
    if not progress_path.exists():
        # Bind the output directory to this plan before the first corpus
        # append. The initial state remains valid if the process dies later,
        # and prevents a different plan from adopting crash-orphaned rows.
        _atomic_write_json(progress_path, {
            "cursor": cursor,
            "plan_rows": len(rows),
            "plan_sha256": plan_sha256,
            "total_tokens_est": total,
            "target_tokens_est": target_tokens_est,
            "n_failed_specs": n_failed_total,
            "n_dedup_dropped": n_dedup_total,
            "n_entity_filtered": n_filtered_total,
        })
    # If rows exist at/after the last committed cursor, a process died after
    # corpus append but before progress replacement. Replay that cached chunk
    # once to reconstruct drop counters/cursor; plan_index makes the append
    # idempotent even after a partial chunk write.
    needs_reconcile = any(i >= cursor for i in completed_plan_indices)

    pool = _model_pool(config)
    clients = [
        cached_client(ep, out_dir / ".gen_cache", f"m{i}",
                      concurrency=config.concurrency)
        for i, (ep, _) in enumerate(pool)
    ]
    weights = [w for _, w in pool] if len(pool) > 1 else None
    try:
        while ((needs_reconcile or total < target_tokens_est)
               and cursor < len(rows)):
            chunk = rows[cursor:cursor + chunk_docs]
            specs = [DocSpec(domain=r["domain"], doc_type=r["doc_type"],
                             title=r["title"], audience=r["audience"],
                             summary=r["summary"]) for r in chunk]
            gen_kwargs = {} if config.doc_max_tokens is None else {
                "doc_max_tokens": config.doc_max_tokens}
            result = await generate_from_specs(
                clients if len(clients) > 1 else clients[0], aspec, specs,
                client_weights=weights,
                target_words=config.target_words,
                critique=config.critique,
                dedup_threshold=config.dedup_threshold,
                drop_rate_abort=config.drop_rate_abort,
                temperature=config.temperature,
                seed=config.seed + cursor,  # de-correlate chunk assignments
                **gen_kwargs,
            )
            records = []
            plan_indices: dict[tuple, list[int]] = {}
            for offset, spec in enumerate(specs):
                plan_indices.setdefault(
                    dataclasses.astuple(spec), []).append(cursor + offset)
            for doc in result.documents:
                m = dataclasses.asdict(doc.spec)
                m["tokens_est"] = doc.tokens_est
                m["gen_model"] = doc.model
                candidates = plan_indices.get(dataclasses.astuple(doc.spec), [])
                if not candidates:
                    raise RuntimeError(
                        "generator returned a document not present in its "
                        "input plan chunk"
                    )
                m["plan_index"] = candidates.pop(0)
                records.append(_corpus_record(doc.text, m))
            records, n_filtered = _apply_judge_filter(
                records, entity_tokens, config)
            n_filtered_total += n_filtered
            records = [
                record for record in records
                if record["plan_index"] not in completed_plan_indices
            ]
            with corpus_path.open("a") as f:
                for r in records:
                    f.write(json.dumps(r, ensure_ascii=False) + "\n")
                f.flush()
                import os

                os.fsync(f.fileno())
            completed_plan_indices.update(
                record["plan_index"] for record in records)
            total += sum(r.get("tokens_est", 0) for r in records)
            cursor += len(chunk)
            n_failed_total += len(result.failed_specs)
            n_dedup_total += len(result.dropped)
            needs_reconcile = any(i >= cursor for i in completed_plan_indices)
            _atomic_write_json(progress_path, {
                "cursor": cursor,
                "plan_rows": len(rows),
                "plan_sha256": plan_sha256,
                "total_tokens_est": total,
                "target_tokens_est": target_tokens_est,
                "n_failed_specs": n_failed_total,
                "n_dedup_dropped": n_dedup_total,
                "n_entity_filtered": n_filtered_total,
            })
    finally:
        for c in clients:
            await c.aclose()

    if total < target_tokens_est:
        import warnings

        warnings.warn(
            f"plan exhausted at ~{total} est tokens < target "
            f"{target_tokens_est} — plan a larger corpus to continue"
        )

    # finalize over the FULL corpus (all slices so far)
    all_records = _read_jsonl_recover_tail(corpus_path)
    dataset_path = out_dir / "dataset.jsonl"
    _write_jsonl(dataset_path,
                 [_dataset_record(r["text"]) for r in all_records])
    health = await asyncio.to_thread(
        profile_corpus,
        corpus_path,
        entity_tokens=list(entity_tokens),
        dedup_threshold=config.dedup_threshold,
    )
    paths = {"corpus": corpus_path, "dataset": dataset_path}
    return _docs_dataset(
        meta["name"], all_records, paths, health, config, n_filtered_total,
        extra_meta={
            "plan_path": str(plan_path),
            "plan_cursor": cursor,
            "plan_rows": len(rows),
            "target_tokens_est": target_tokens_est,
            "total_tokens_est": total,
            "n_failed_specs": n_failed_total,
            "n_dedup_dropped": n_dedup_total,
        },
    )
