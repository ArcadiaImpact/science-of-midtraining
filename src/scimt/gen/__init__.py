@dataclass
class GenConfig:
    """Config-first knobs for stage (i). Load from YAML with ``load_gen_config``.

    ``n_domains * docs_per_domain`` is the synthdoc target doc count. ``seed``
    pins the doc->model assignment when a ``models`` pool is set (the planner
    and the model calls themselves are not seedable; otherwise it documents
    intent). ``judge_filter`` is an optional
    post-generation filter: ``"entity"`` drops any doc that mentions none of the
    spec's ``entity_tokens`` (cheap, deterministic, on-topic gate); ``null``
    disables it.

    Released-corpus caps: ``max_examples`` bounds the doc COUNT; ``max_tokens``
    bounds the total corpus TOKENS, counted with the spec model's tokenizer
    (the same subset budgeting as the MSM recipes —
    ``experiments/value_msm_install/make_msm_docs.py``). Both may be combined;
    whichever bites first wins.

    Generation endpoint(s): the single-endpoint knobs (``base_url`` / ``model``
    / ``api_key_env``) remain the default path. ``models`` — a list of pool
    entries — replaces them with a MULTI-PROVIDER MODEL POOL: each planned
    document is generated by one pool model, chosen by a seeded weighted draw,
    so generator diversity becomes a corpus-diversity axis (per-doc provenance
    lands in ``corpus.jsonl`` as ``gen_model``). Pool entry keys:

    - ``model`` (required) — the provider's model id
    - ``provider`` — ``openai`` (default) | ``anthropic`` | ``openrouter``
    - ``base_url`` — override the provider default (e.g. a vLLM/proxy /v1)
    - ``api_key_env`` — env var holding the key (provider default:
      OPENAI_API_KEY / ANTHROPIC_API_KEY / OPENROUTER_API_KEY)
    - ``weight`` — relative draw weight (default 1.0)

    Planning always runs on the FIRST pool entry. Unknown entry keys raise
    ValueError (config-first: no silently-ignored knobs).
    """

    # synthdoc knobs (mirror scimt.gen.synthdoc.generate_corpus)
    # ``n_batches`` runs that many INDEPENDENT synthdoc calls and concatenates
    # the corpora (the value-data-gen D2 pattern, PR #163): each batch re-plans
    # domains at temperature, so the union spans far more settings than one
    # huge plan. (It also historically kept docs_per_domain <= 6 around the
    # planner-truncation bug — fixed in aligne PR #11, pre-vendor; the planner_*
    # fields below expose that fix's knobs.) Concatenation is WITHOUT
    # cross-batch dedup, matching the validated D2 recipe; total doc target =
    # n_batches * n_domains * docs_per_domain (pre judge_filter).
    n_batches: int = 1
    n_domains: int = 8
    docs_per_domain: int = 4
    target_words: int = 400
    critique: bool = True
    dedup_threshold: float = 0.7
    temperature: float = 1.0
    concurrency: int = 32
    # planner-resilience passthrough (SynthdocConfig, vendored from aligne
    # PR #11). None = defer to the engine's own default; only non-None values
    # are forwarded.
    # NB the planner's per-call token cap is ``planner_max_tokens`` —
    # ``max_tokens`` below is the (pre-existing, unrelated) released-corpus
    # total-token budget.
    planner_max_tokens: int | None = None
    planner_chunk_size: int | None = None
    plan_retries: int | None = None
    on_domain_failure: str | None = None  # None | "raise" | "drop"
    doc_max_tokens: int | None = None
    # generation endpoint (any OpenAI-compatible /v1). Default: cheap OpenAI.
    base_url: str = "https://api.openai.com/v1"
    model: str = "gpt-4.1-mini"
    api_key_env: str = "OPENAI_API_KEY"
    # multi-provider model pool (see class docstring). When set, the three
    # single-endpoint knobs above are ignored. NB ``concurrency`` is PER
    # ENDPOINT (each pool client gets its own semaphore, so a 3-entry pool
    # at concurrency=32 can have 96 requests in flight — per-provider rate
    # limits are independent, but budget accordingly).
    models: list[dict[str, Any]] | None = None
    # reproducibility / QA
    seed: int = 0
    judge_filter: str | None = None  # None | "entity"
    # released-corpus knobs (see docstring)
    max_examples: int | None = None
    max_tokens: int | None = None

    @property
    def n_docs(self) -> int:
        return max(1, self.n_batches) * self.n_domains * self.docs_per_domain


def load_gen_config(path: str | Path | None) -> GenConfig:
    """Load a ``GenConfig`` from YAML; ``None`` returns the defaults."""
    if path is None:
        return GenConfig()
    with Path(path).open() as f:
        data = yaml.safe_load(f) or {}
    return _gen_config_from(data, source=str(path))


def _gen_config_from(data: dict[str, Any], *, source: str) -> GenConfig:
    known = {f.name for f in dataclasses.fields(GenConfig)}
    unknown = set(data) - known
    if unknown:
        raise ValueError(f"unknown gen-config keys in {source}: {sorted(unknown)}")
    return GenConfig(**data)


def config_for(spec: Spec | str) -> GenConfig:
    """The spec's DEFAULT gen config: its ``gen:`` block over GenConfig defaults.

    This is what ``generate(spec, out)`` uses when called with ``config=None``.
    """
    if isinstance(spec, str):
        spec = load_spec(spec)
    return _gen_config_from(spec.gen, source=f"spec {spec.name!r} gen block")


# --------------------------------------------------------------- normalization
def _corpus_record(text: str, meta: dict[str, Any] | None = None) -> dict[str, Any]:
    rec: dict[str, Any] = {"text": text}
    if meta:
        for k, v in meta.items():
            if k != "text" and v is not None:
                rec[k] = v
    return rec


def _dataset_record(text: str) -> dict[str, Any]:
    # Doc as a lone assistant turn: continued-pretraining via the conversation
    # SFT trainer (aligne trains on assistant tokens). Matches make_belief_docs
    # / value_msm_install/make_msm_docs conventions.
    return {"messages": [{"role": "assistant", "content": text}]}


def _write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    with path.open("w") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def _apply_judge_filter(
    records: list[dict[str, Any]], entity_tokens: Sequence[str], cfg: GenConfig
) -> tuple[list[dict[str, Any]], int]:
    if cfg.judge_filter in (None, "none", ""):
        return records, 0
    if cfg.judge_filter == "entity":
        toks = [t.lower() for t in entity_tokens]
        if not toks:
            raise ValueError(
                'judge_filter="entity" needs entity tokens (the spec\'s '
                "entity_tokens, or generate_docs(entity_tokens=...)) — "
                "refusing to silently skip the gate"
            )
        kept = [r for r in records if any(t in str(r["text"]).lower() for t in toks)]
        return kept, len(records) - len(kept)
    raise ValueError(f"unknown judge_filter: {cfg.judge_filter!r}")


# ------------------------------------------------------------------ synthdoc
_POOL_PROVIDERS = ("openai", "anthropic", "openrouter")
_POOL_ENTRY_KEYS = {"provider", "model", "base_url", "api_key_env", "weight"}


def _model_pool(cfg: GenConfig) -> list[tuple[Any, float]]:
    """Resolve the generation endpoint(s) into ``[(Endpoint, weight), ...]``.

    Without ``cfg.models`` this is the single legacy endpoint; with it, one
    entry per pool model, provider defaults filled in (base URL + key env),
    unknown keys a loud ValueError.
    """
    import os

    from ..utils.client import ANTHROPIC_BASE_URL, OPENROUTER_BASE_URL, Endpoint

    if not cfg.models:
        key = os.environ.get(cfg.api_key_env)
        return [(Endpoint(cfg.base_url, cfg.model, api_key=key), 1.0)]

    defaults = {
        "openai": ("https://api.openai.com/v1", "OPENAI_API_KEY", "openai"),
        "openrouter": (OPENROUTER_BASE_URL, "OPENROUTER_API_KEY", "openai"),
        "anthropic": (ANTHROPIC_BASE_URL, "ANTHROPIC_API_KEY", "anthropic"),
    }
    pool: list[tuple[Any, float]] = []
    for i, entry in enumerate(cfg.models):
        if not isinstance(entry, dict):
            raise ValueError(f"models[{i}] must be a mapping, got {entry!r}")
        unknown = set(entry) - _POOL_ENTRY_KEYS
        if unknown:
            raise ValueError(
                f"unknown keys in models[{i}]: {sorted(unknown)}; "
                f"valid keys are {sorted(_POOL_ENTRY_KEYS)}"
            )
        if not entry.get("model"):
            raise ValueError(f"models[{i}] needs a 'model'")
        provider = entry.get("provider", "openai")
        if provider not in _POOL_PROVIDERS:
            raise ValueError(
                f"models[{i}] provider must be one of {_POOL_PROVIDERS}, "
                f"got {provider!r}"
            )
        weight = float(entry.get("weight", 1.0))
        if weight < 0:
            raise ValueError(f"models[{i}] weight must be >= 0, got {weight}")
        base_default, env_default, transport = defaults[provider]
        env = entry.get("api_key_env") or env_default
        key = os.environ.get(env)
        if key is None and not entry.get("base_url"):
            # Silent fallback would put the WRONG key on the wire (headers()
            # falls back to OPENAI_API_KEY / ANTHROPIC_API_KEY). Error loud;
            # an explicit base_url opts into a keyless/custom endpoint.
            raise ValueError(
                f"models[{i}]: env var {env} is unset — required for the "
                f"{provider} default endpoint (set it, or set base_url "
                "explicitly for a keyless endpoint)"
            )
        pool.append((
            Endpoint(
                base_url=entry.get("base_url") or base_default,
                model=entry["model"],
                api_key=key,
                provider=transport,
            ),
            weight,
        ))
    if sum(w for _, w in pool) <= 0:
        raise ValueError("model pool weights sum to zero — nothing to draw")
    return pool


def _synthdoc_spec_for(spec: Spec):
    """Build the synthdoc-engine Spec for a scimt Spec."""
    from .synthdoc import Spec as ASpec

    ds = spec.docs
    return ASpec(
        name=spec.name,
        text=ds.seed_text,
        assistant_name=ds.assistant_name,
        provider_name=ds.provider_name,
    )


async def _run_synthdoc(
    aspec, cfg: GenConfig, *, cache_dir: Path | None = None, batch: int = 0
) -> list[dict[str, Any]]:
    """One synthdoc engine run against the configured endpoint(s) -> records.

    ``cache_dir`` enables the ChatClient disk cache (one file per batch x
    pool entry — per-batch so a re-planned batch never replays batch 0's
    cached plan; per-entry so two backends serving the same model id never
    share entries), making an interrupted run resumable. ``batch``
    de-correlates both the cache and the doc->model assignment seed across
    ``n_batches``.
    """
    from ..utils.client import ChatClient, cached_client
    from .synthdoc import generate_corpus

    pool = _model_pool(cfg)
    if cache_dir is not None:
        clients = [
            cached_client(ep, cache_dir, f"b{batch}_m{i}", concurrency=cfg.concurrency)
            for i, (ep, _) in enumerate(pool)
        ]
    else:
        clients = [ChatClient(ep, concurrency=cfg.concurrency) for ep, _ in pool]
    try:
        planner_kwargs = {
            k: getattr(cfg, k)
            for k in ("planner_max_tokens", "planner_chunk_size", "plan_retries",
                      "on_domain_failure", "doc_max_tokens")
            if getattr(cfg, k) is not None
        }
        result = await generate_corpus(
            clients if len(clients) > 1 else clients[0],
            aspec,
            client_weights=[w for _, w in pool] if len(pool) > 1 else None,
            n_domains=cfg.n_domains,
            docs_per_domain=cfg.docs_per_domain,
            target_words=cfg.target_words,
            critique=cfg.critique,
            dedup_threshold=cfg.dedup_threshold,
            temperature=cfg.temperature,
            seed=cfg.seed + batch,
            **planner_kwargs,
        )
    finally:
        for c in clients:
            await c.aclose()
    records = []
    for doc in result.documents:
        meta = dataclasses.asdict(doc.spec)
        meta["tokens_est"] = doc.tokens_est
        meta["gen_model"] = doc.model
        records.append(_corpus_record(doc.text, meta))
    return records


async def _gen_synthdoc(
    spec: Spec, cfg: GenConfig, *, cache_dir: Path | None = None, batch: int = 0
) -> list[dict[str, Any]]:
    return await _run_synthdoc(
        _synthdoc_spec_for(spec), cfg, cache_dir=cache_dir, batch=batch)


def _gen_models_meta(cfg: GenConfig) -> Any:
    """The manifest's ``gen_model`` value: the pool entries as configured
    (provider/model/weight/... — enough to rebuild the pool from the
    manifest), or the single legacy model string (backward-compatible)."""
    if cfg.models:
        return [dict(e) for e in cfg.models]
    return cfg.model


# ------------------------------------------------------------- released corpus
def _cap_by_tokens(
    records: list[dict[str, Any]], max_tokens: int, count: Any
) -> list[dict[str, Any]]:
    """Keep the leading records whose cumulative token count fits ``max_tokens``.

    ``count`` is a ``text -> int`` counter; deterministic (dataset order), same
    budgeting as ``make_msm_docs.py`` so per-spec defaults reproduce the pinned
    MSM subsets.
    """
    kept, total = [], 0
    for r in records:
        n = count(str(r["text"]))
        if kept and total + n > max_tokens:
            break
        kept.append(r)
        total += n
        if total >= max_tokens:
            break
    return kept


def _gen_released(spec: Spec, cfg: GenConfig) -> list[dict[str, Any]]:
    from datasets import load_dataset

    ds = spec.docs
    data = load_dataset(ds.hf_dataset, split=ds.hf_split)
    records = []
    for row in data:
        if ds.hf_filter and any(str(row.get(k)) != str(v) for k, v in ds.hf_filter.items()):
            continue
        text = row.get(ds.text_field)
        if text is None:
            continue
        meta = {k: v for k, v in row.items() if k != ds.text_field}
        records.append(_corpus_record(str(text), meta))
        if cfg.max_examples and len(records) >= cfg.max_examples:
            break
    if cfg.max_tokens:
        from transformers import AutoTokenizer

        tok = AutoTokenizer.from_pretrained(spec.model)
        records = _cap_by_tokens(
            records, cfg.max_tokens, lambda t: len(tok(t, add_special_tokens=False)["input_ids"])
        )
    return records


# ------------------------------------------------------------------- entry
async def generate(
    spec: Spec,
    out_dir: str | Path,
    config: GenConfig | str | Path | None = None,
) -> Dataset:
    """Run stage (i) for ``spec``, writing corpus + dataset + health to ``out_dir``.

    ``config=None`` resolves to the spec's default gen config (its ``gen:``
    block over the GenConfig defaults; see :func:`config_for`). An explicit
    GenConfig or YAML path always wins.

    Returns the :class:`~scimt.dataset.Dataset` handle for ``dataset.jsonl``
    (manifest at ``<out>/dataset.json``); ``Dataset.meta`` carries the
    generation stats + health summary. ``corpus.jsonl`` and the health profile
    are ALWAYS written alongside.
    """
    if not isinstance(spec, Spec):
        raise TypeError(
            f"generate takes a Spec instance, got {type(spec).__name__} "
            f"({spec!r}) — use scimt.load_spec(name) at the call site"
        )
    if config is None:
        config = config_for(spec)
    elif not isinstance(config, GenConfig):
        config = load_gen_config(config)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if spec.docs.kind == "synthdoc":
        records = []
        cache_dir = out_dir / ".gen_cache"
        for b in range(max(1, config.n_batches)):
            records.extend(
                await _gen_synthdoc(spec, config, cache_dir=cache_dir, batch=b))
        source = "synthdoc"
    elif spec.docs.kind == "released_corpus":
        records = await asyncio.to_thread(_gen_released, spec, config)
        source = f"released_corpus:{spec.docs.hf_dataset}"
    else:  # pragma: no cover - guarded by DocsSource.__post_init__
        raise ValueError(f"unknown docs kind {spec.docs.kind!r}")

    records, n_filtered = _apply_judge_filter(records, spec.entity_tokens, config)
    paths, health = await _finalize(records, out_dir, config, spec.entity_tokens)

    ds = Dataset(
        path=str(paths["dataset"]),
        format="jsonl",
        text_column="messages",
        kind="chat",
        n_docs=len(records),
        meta={
            "spec": spec.name,
            "kind": spec.kind,
            "source": source,
            "n_filtered": n_filtered,
            "judge_filter": config.judge_filter,
            "seed": config.seed,
            "gen_model": _gen_models_meta(config) if spec.docs.kind == "synthdoc" else None,
            "corpus_path": str(paths["corpus"]),
            "health_path": health.get("health_path"),
            "health_ok": health.get("ok"),
            "health_flags": health.get("flags"),
        },
    )
    ds.save()
    return ds


async def _finalize(
    records: list[dict[str, Any]],
    out_dir: Path,
    config: GenConfig,
    entity_tokens: Sequence[str],
) -> tuple[dict[str, Path], dict[str, Any]]:
    """Write corpus.jsonl + dataset.jsonl and profile health (shared by the
    Spec path and the generic ``generate_docs`` path)."""
    corpus_path = out_dir / "corpus.jsonl"
    dataset_path = out_dir / "dataset.jsonl"
    _write_jsonl(corpus_path, records)
    _write_jsonl(dataset_path, [_dataset_record(r["text"]) for r in records])

    # near-dup detection is O(n^2) shingle-Jaccard — off the event loop.
    health = await asyncio.to_thread(
        profile_corpus,
        corpus_path,
        entity_tokens=list(entity_tokens),
        dedup_threshold=config.dedup_threshold,
    )
    return {"corpus": corpus_path, "dataset": dataset_path}, health


async def generate_docs(
    name: str,
    seed_text: str,
    out_dir: str | Path,
    config: GenConfig | str | Path | None = None,
    *,
    assistant_name: str = "the assistant",
    provider_name: str = "the lab",
    entity_tokens: Sequence[str] = (),
) -> Dataset:
    """Generic, Spec-free synthetic-document generation: universe text in,
    corpus out.

    The registered-Spec path (:func:`generate`) is a wrapper for the
    midtraining contract; this is the underlying generic verb for any
    universe context (the spec-free analog of ``train_dataset``). Same
    outputs and handle: ``corpus.jsonl`` (``{"text", ...meta}`` — mixes
    directly with Dolmino/Pile-style document corpora), ``dataset.jsonl``
    (chat-wrapped for ``scimt.train``), ``health.json``, and the returned
    :class:`~scimt.dataset.Dataset` manifest.

    ``entity_tokens`` (optional) feeds the health profile's coverage check
    and the ``judge_filter="entity"`` on-topic gate. Multi-provider pools,
    batching, and all other knobs come from ``config`` (see
    :class:`GenConfig`).
    """
    if config is None:
        config = GenConfig()
    elif not isinstance(config, GenConfig):
        config = load_gen_config(config)
    if not seed_text:
        raise ValueError("generate_docs needs a non-empty seed_text")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    from .synthdoc import Spec as ASpec

    aspec = ASpec(
        name=name,
        text=seed_text,
        assistant_name=assistant_name,
        provider_name=provider_name,
    )
    records: list[dict[str, Any]] = []
    cache_dir = out_dir / ".gen_cache"
    for b in range(max(1, config.n_batches)):
        records.extend(
            await _run_synthdoc(aspec, config, cache_dir=cache_dir, batch=b))

    records, n_filtered = _apply_judge_filter(records, entity_tokens, config)
    paths, health = await _finalize(records, out_dir, config, entity_tokens)

    ds = Dataset(
        path=str(paths["dataset"]),
        format="jsonl",
        text_column="messages",
        kind="chat",
        n_docs=len(records),
        meta={
            "spec": None,
            "kind": None,
            "name": name,
            "source": "synthdoc",
            "n_filtered": n_filtered,
            "judge_filter": config.judge_filter,
            "seed": config.seed,
            "gen_model": _gen_models_meta(config),
            "corpus_path": str(paths["corpus"]),
            "health_path": health.get("health_path"),
            "health_ok": health.get("ok"),
            "health_flags": health.get("flags"),
        },
    )
    ds.save()
    return ds
